def test_uv_installs_the_project_with_the_wheels_of_its_extra_and_takes_a_rebuilt_one(
    tmp_path: Path, offline_uv: Path
) -> None:
    """The claim the option rests on, with the real uv, offline: the extra installs each wheel from its file — a
    wheel only another wheel needs included —, a wheel rebuilt under the same version is installed again, and
    without the extra no source applies."""
    uv = str(Path(sys.executable).with_name("uv"))
    app = tmp_path / "app"
    _project(tmp_path, "app", deps=["libz"])
    sources = tmp_path / "sources"
    _project(sources, "libz", deps=["liby"], modules={"libz/__init__.py": "import liby\n"})
    _project(sources, "liby", modules={"liby/__init__.py": "V = 'a'\n"})
    for name in ("libz", "liby"):
        w.build_wheel(uv, sources / name, app / "wheels")
    path = app / "pyproject.toml"
    path.write_text(path.read_text() + '[tool.aisland]\nmanual-extras = ["wheels"]\n')
    wheels = [we.ExtraWheel(n, f"{n}-0.1.0-py3-none-any.whl") for n in ("libz", "liby")]
    we.check_extra(path, "wheels", ["libz", "liby"])
    we.write_extra(path, "wheels", wheels, "aisland wheels build app --extra wheels")
    venv = tmp_path / "venv"
    subprocess.run([uv, "venv", "-q", str(venv)], check=True)
    python = venv / "bin" / "python"
    env = {**os.environ, "VIRTUAL_ENV": str(venv)}
    index = ["--no-index", "--find-links", str(offline_uv)]

    def _install(*args: str) -> str:
        done = subprocess.run(
            [uv, "pip", "install", "--python", str(python), *index, *args],
            cwd=tmp_path,
            env=env,
            capture_output=True,
            text=True,
        )
        assert done.returncode == 0, done.stderr
        return done.stderr

    def _value() -> str:
        return subprocess.run([python, "-c", "import libz, liby; print(liby.V)"], capture_output=True, text=True).stdout

    without = subprocess.run(
        [uv, "pip", "install", "--python", str(python), *index, "--dry-run", "-e", "./app"],
        cwd=tmp_path,
        env=env,
        capture_output=True,
        text=True,
    )
    assert without.returncode != 0 and "libz" in without.stderr  # no source without the extra: uv looks on the index

    said = _install("-e", "./app[wheels]")
    assert "+ liby==0.1.0 (from file://" in said and "+ libz==0.1.0 (from file://" in said
    assert _value() == "a\n"

    (sources / "liby" / "liby" / "__init__.py").write_text("V = 'b'\n")
    w.build_wheel(uv, sources / "liby", app / "wheels")
    said = _install("-e", "./app[wheels]")
    assert "~ liby==0.1.0 (from file://" in said
    assert _value() == "b\n"
