"""Tests for `aisland wheels build PROJECT --extra NAME` (aisland/wheels_extra.py): the extra and its uv sources
written into the project's `pyproject.toml`, so `uv pip install -e ./PROJECT[NAME]` installs every wheel built.

Three groups: the writer over hand-written files; the build run with faked builds (what it refuses, writes and
commits); the real uv, offline, installing a project with its extra from wheels written by hand.
"""

from __future__ import annotations

import os
import subprocess
import sys
import tomllib
from pathlib import Path
from typing import List

import click
import pytest
from click.testing import CliRunner

from aisland import wheels as w
from aisland import wheels_extra as we
from aisland.cli import main

from . import test_wheels
from .test_wheels import _commit, _git, _no_builds, _project, _pypi, _workspace, offline_uv

__all__ = ["offline_uv"]  # the fixture, imported so the end-to-end test here can ask for it

_COMMAND = "aisland wheels build app --all --include-project --extra wheels"

#: A pyproject shaped like a real one: a comment above the table after the extras belongs to that table.
_PYPROJECT = """\
[project]
name = "app"
version = "0.1.0"
dependencies = ["liba"]

[project.optional-dependencies]
remote = ["liba @ git+https://example.com/liba.git"]
dev = [
    "pytest",
]

# `uv run` installs the default groups beside the project.
[dependency-groups]
annotate = ["viewer"]

[tool.aisland]
manual-extras = ["remote", "wheels"]
"""

_WHEELS = [we.ExtraWheel("liba", "liba-0.1.0-py3-none-any.whl"), we.ExtraWheel("lib-b", "lib_b-2.0-py3-none-any.whl")]


def _pyproject(tmp_path: Path, text: str = _PYPROJECT) -> Path:
    path = tmp_path / "pyproject.toml"
    path.write_text(text)
    return path


def _read(path: Path) -> dict:
    return tomllib.loads(path.read_text())


# --- the writer --------------------------------------------------------------------------------


class TestWriteExtra:
    def test_the_extra_names_each_wheel_and_each_source_is_its_file_under_the_extra(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path)

        assert we.write_extra(path, "wheels", _WHEELS, _COMMAND) is True

        data = _read(path)
        assert data["project"]["optional-dependencies"]["wheels"] == ["lib-b", "liba"]
        assert data["tool"]["uv"]["sources"] == {
            "lib-b": [{"path": "wheels/lib_b-2.0-py3-none-any.whl", "extra": "wheels"}],
            "liba": [{"path": "wheels/liba-0.1.0-py3-none-any.whl", "extra": "wheels"}],
        }
        assert data["project"]["optional-dependencies"]["dev"] == ["pytest"]
        assert data["dependency-groups"] == {"annotate": ["viewer"]}

    def test_the_extra_ends_its_table_and_the_comment_above_the_next_table_stays_with_it(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path)
        we.write_extra(path, "wheels", _WHEELS, _COMMAND)

        text = path.read_text()
        assert text.startswith(_PYPROJECT.split("\n# `uv run`")[0].rstrip("\n").rsplit("]", 1)[0])
        assert (
            "dev = [\n"
            '    "pytest",\n'
            "]\n"
            f"{we.BEGIN}: the `wheels` extra — `uv pip install -e .[wheels]` installs every wheel in wheels/\n"
            f"#     Generated by: {_COMMAND}\n"
            "#     Source: aisland/aisland/wheels_extra.py (render_blocks)\n"
            f"#     To regenerate: {_COMMAND}\n"
            "wheels = [\n"
            '    "lib-b",\n'
            '    "liba",\n'
            "]\n"
            f"{we.END}\n"
            "\n"
            "# `uv run` installs the default groups beside the project.\n"
            "[dependency-groups]\n"
        ) in text
        assert text.endswith(
            '[tool.aisland]\nmanual-extras = ["remote", "wheels"]\n'
            "\n"
            "[tool.uv.sources]\n"
            f"{we.BEGIN}: each wheel of the `wheels` extra, from its file in wheels/\n"
            f"#     Generated by: {_COMMAND}\n"
            "#     Source: aisland/aisland/wheels_extra.py (render_blocks)\n"
            f"#     To regenerate: {_COMMAND}\n"
            'lib-b = [{ path = "wheels/lib_b-2.0-py3-none-any.whl", extra = "wheels" }]\n'
            'liba = [{ path = "wheels/liba-0.1.0-py3-none-any.whl", extra = "wheels" }]\n'
            f"{we.END}\n"
        )

    def test_a_rerun_of_the_same_wheels_changes_nothing(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path)
        we.write_extra(path, "wheels", _WHEELS, _COMMAND)
        first = path.read_bytes()

        assert we.write_extra(path, "wheels", _WHEELS, _COMMAND) is False
        assert path.read_bytes() == first

    def test_a_new_version_replaces_the_blocks_and_nothing_else(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path)
        we.write_extra(path, "wheels", _WHEELS, _COMMAND)
        before = path.read_text()

        assert we.write_extra(path, "wheels", [we.ExtraWheel("liba", "liba-0.2.0-py3-none-any.whl")], _COMMAND)

        after = path.read_text()
        assert _read(path)["project"]["optional-dependencies"]["wheels"] == ["liba"]
        assert _read(path)["tool"]["uv"]["sources"] == {
            "liba": [{"path": "wheels/liba-0.2.0-py3-none-any.whl", "extra": "wheels"}]
        }
        removed = set(before.splitlines()) - set(after.splitlines())
        assert removed == {
            '    "lib-b",',
            'lib-b = [{ path = "wheels/lib_b-2.0-py3-none-any.whl", extra = "wheels" }]',
            'liba = [{ path = "wheels/liba-0.1.0-py3-none-any.whl", extra = "wheels" }]',
        }

    def test_the_sources_join_a_sources_table_the_project_has_and_keep_its_entries(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path, _PYPROJECT + '\n[tool.uv.sources]\nviewer = { path = "../viewer" }\n')

        we.write_extra(path, "wheels", _WHEELS, _COMMAND)

        sources = _read(path)["tool"]["uv"]["sources"]
        assert sources["viewer"] == {"path": "../viewer"}
        assert sources["liba"] == [{"path": "wheels/liba-0.1.0-py3-none-any.whl", "extra": "wheels"}]
        assert path.read_text().count("[tool.uv.sources]") == 1

    def test_a_project_without_extras_gets_the_table(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path, '[project]\nname = "app"\nversion = "0.1.0"\n')

        we.write_extra(path, "wheels", _WHEELS[:1], _COMMAND)

        assert _read(path)["project"]["optional-dependencies"] == {"wheels": ["liba"]}

    def test_no_wheel_is_an_empty_extra(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path)

        we.write_extra(path, "wheels", [], _COMMAND)

        assert _read(path)["project"]["optional-dependencies"]["wheels"] == []
        assert "wheels = []\n" in path.read_text()

    def test_a_name_toml_cannot_take_bare_is_quoted(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path)

        we.write_extra(path, "wheels", [we.ExtraWheel("acme.tools", "acme.tools-1.0-py3-none-any.whl")], _COMMAND)

        assert '"acme.tools" = [{ path' in path.read_text()
        assert list(_read(path)["tool"]["uv"]["sources"]) == ["acme.tools"]


class TestCheckExtra:
    def test_a_project_that_does_not_mark_the_extra_manual_is_refused_at_the_line(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path, _PYPROJECT.replace('["remote", "wheels"]', '["remote"]'))

        with pytest.raises(click.ClickException) as error:
            we.check_extra(path, "wheels", ["liba"])

        assert error.value.message == (
            f"{path}:17: --extra wheels needs 'wheels' in [tool.aisland] manual-extras — `aisland setup` would "
            "otherwise install it, and its wheels would replace the workspace's checkouts"
        )

    def test_without_a_tool_aisland_table_the_refusal_names_the_first_line(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path, '[project]\nname = "app"\n')

        with pytest.raises(click.ClickException, match=rf"^{path}:1: --extra wheels needs 'wheels'"):
            we.check_extra(path, "wheels", [])

    def test_an_extra_written_by_hand_is_refused_at_its_line(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path, _PYPROJECT.replace("dev = [\n", 'wheels = ["liba"]\ndev = [\n'))

        with pytest.raises(click.ClickException) as error:
            we.check_extra(path, "wheels", ["liba"])

        assert error.value.message == f"{path}:8: the extra 'wheels' is written by hand; --extra writes it — remove it"

    def test_a_source_written_by_hand_for_a_wheel_is_refused_at_its_line(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path, _PYPROJECT + '\n[tool.uv.sources]\nliba = { path = "../liba" }\n')

        with pytest.raises(click.ClickException) as error:
            we.check_extra(path, "wheels", ["liba", "lib-b"])

        assert error.value.message == (
            f"{path}:20: [tool.uv.sources] already has liba; --extra wheels writes a source for each wheel — "
            "remove it"
        )

    def test_the_generated_blocks_are_no_hand_written_keys(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path)
        we.write_extra(path, "wheels", _WHEELS, _COMMAND)

        we.check_extra(path, "wheels", ["liba", "lib-b"])

    def test_a_name_that_is_no_normalized_extra_is_refused(self, tmp_path: Path) -> None:
        with pytest.raises(click.ClickException, match=r"--extra 'Wheels' is no extra name: .* \(as 'wheels'\)"):
            we.check_extra(_pyproject(tmp_path), "Wheels", [])

    @pytest.mark.parametrize(
        ("text", "message"),
        [
            (f"{we.BEGIN}\nx = 1\n", "2: a generated block is never closed"),
            (f"{we.END}\n", "2: a generated block ends that never started"),
            (f"{we.BEGIN}\n{we.BEGIN}\n{we.END}\n", "3: a generated block starts inside the one opened at line 2"),
        ],
    )
    def test_a_broken_marker_is_refused_at_its_line(self, tmp_path: Path, text: str, message: str) -> None:
        path = _pyproject(tmp_path, "[project]\n" + text)

        with pytest.raises(click.ClickException, match=f"^{path}:{message}"):
            we.check_extra(path, "wheels", [])

    def test_a_file_toml_cannot_read_is_named(self, tmp_path: Path) -> None:
        path = _pyproject(tmp_path, "[project\n")

        with pytest.raises(click.ClickException, match=f"^{path}: "):
            we.check_extra(path, "wheels", [])


# --- the build run -----------------------------------------------------------------------------


def _manual(root: Path, extras: str = '["wheels"]') -> None:
    path = root / "app" / "pyproject.toml"
    path.write_text(path.read_text() + f"[tool.aisland]\nmanual-extras = {extras}\n")


def _app_and_libx(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """`app` needs `libx`, which PyPI lacks; app marks `wheels` manual."""
    root = _workspace(tmp_path, "app", "libx")
    _project(root, "app", deps=["libx"])
    _project(root, "libx")
    _manual(root)
    _commit(root / "app")
    _commit(root / "libx")
    _pypi(monkeypatch, {})
    return root


class TestTheBuildRun:
    def test_the_extra_is_written_and_every_generated_file_names_the_command(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _app_and_libx(tmp_path, monkeypatch)
        test_wheels.TestTheRunWithFakedBuilds._fake_builds(monkeypatch, {})

        report = w.vendor_wheels(root, "app", extra="wheels")

        data = _read(root / "app" / "pyproject.toml")
        assert data["project"]["optional-dependencies"]["wheels"] == ["libx"]
        assert data["tool"]["uv"]["sources"] == {
            "libx": [{"path": "wheels/libx-0.1.0-py3-none-any.whl", "extra": "wheels"}]
        }
        assert (report.extra, report.extra_changed) == ("wheels", True)
        folder = root / "app" / "wheels"
        for name in ("README.md", "wheels.yaml", "install.py"):
            assert "To regenerate: aisland wheels build app --extra wheels\n" in (folder / name).read_text(), name
        readme = (folder / "README.md").read_text()
        assert "    uv pip install -e ./app[wheels]\n" in readme
        assert "    python wheels/install.py\n" in readme
        assert w.render_report(report).endswith(
            "\nThe extra wheels (1 wheel) written into app/pyproject.toml; install it with: "
            "uv pip install -e ./app[wheels]\n"
        )
        assert report.to_dict()["extra"] == "wheels"

    def test_a_rerun_says_the_extra_is_unchanged(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        root = _app_and_libx(tmp_path, monkeypatch)
        test_wheels.TestTheRunWithFakedBuilds._fake_builds(monkeypatch, {})
        w.vendor_wheels(root, "app", extra="wheels")

        report = w.vendor_wheels(root, "app", extra="wheels")

        assert report.extra_changed is False
        assert "The extra wheels (1 wheel) unchanged in app/pyproject.toml" in w.render_report(report)

    def test_without_the_option_the_pyproject_and_every_file_are_what_they_were(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _app_and_libx(tmp_path, monkeypatch)
        test_wheels.TestTheRunWithFakedBuilds._fake_builds(monkeypatch, {})
        pyproject = (root / "app" / "pyproject.toml").read_bytes()

        report = w.vendor_wheels(root, "app")

        assert (root / "app" / "pyproject.toml").read_bytes() == pyproject
        assert report.extra is None and "The extra" not in w.render_report(report)
        assert "uv pip install" not in (root / "app" / "wheels" / "README.md").read_text()
        assert "To regenerate: aisland wheels build app\n" in (root / "app" / "wheels" / "install.py").read_text()

    def test_an_extra_the_project_does_not_mark_manual_is_refused_before_anything_is_built(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _app_and_libx(tmp_path, monkeypatch)
        _no_builds(monkeypatch)

        with pytest.raises(click.ClickException, match=r"--extra dev needs 'dev' in \[tool.aisland\] manual-extras"):
            w.vendor_wheels(root, "app", extra="dev")

        assert not (root / "app" / "wheels").exists()

    def test_commit_commits_the_pyproject_with_the_wheels(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _app_and_libx(tmp_path, monkeypatch)
        test_wheels.TestTheRunWithFakedBuilds._fake_builds(monkeypatch, {})
        (root / "app" / "notes.txt").write_text("not mine")

        report = w.vendor_wheels(root, "app", extra="wheels", commit=True)

        assert report.committed is not None
        files = _git(root / "app", "show", "--name-only", "--format=%s", "HEAD").splitlines()
        assert files[0] == "chore: wheels built with aisland wheels build app --extra wheels"
        assert "pyproject.toml" in files and "wheels/libx-0.1.0-py3-none-any.whl" in files
        assert "notes.txt" not in files
        assert _git(root / "app", "status", "--porcelain").splitlines() == ["?? notes.txt"]

    def test_commit_refuses_a_pyproject_with_changes_of_its_own_before_anything_is_built(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _app_and_libx(tmp_path, monkeypatch)
        path = root / "app" / "pyproject.toml"
        path.write_text(path.read_text() + "# mine\n")
        _no_builds(monkeypatch)

        with pytest.raises(click.ClickException) as error:
            w.vendor_wheels(root, "app", extra="wheels", commit=True)

        assert error.value.message == (
            "app/pyproject.toml has changes no commit holds; --commit would commit them with the extra wheels:\n"
            "     M pyproject.toml\n"
            "Commit or stash them first."
        )

    def test_the_bundle_command_carries_the_extra(self) -> None:
        assert w.bundle_command("app", "all", True, "wheels") == (
            "aisland wheels build app --all --include-project --extra wheels --bundle"
        )


class TestCli:
    def test_the_option_reaches_the_run_and_the_regenerate_line_is_a_command_the_cli_accepts(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        seen: List[dict] = []

        def _run(root: Path, project: str, **kwargs: object) -> w.WheelsReport:
            seen.append(kwargs)
            return test_wheels._report(import_failures=[])

        monkeypatch.setattr(w, "vendor_wheels", _run)
        argv = w.regenerate_command("app", "all", True, "wheels").split()[1:]

        result = CliRunner().invoke(main, argv)

        assert result.exit_code == 0, result.output
        assert seen[0]["extra"] == "wheels" and seen[0]["include_project"] is True and seen[0]["scope"] == "all"

    def test_the_help_names_the_option(self) -> None:
        result = CliRunner().invoke(main, ["wheels", "build", "--help"])

        assert "--extra NAME" in result.output


