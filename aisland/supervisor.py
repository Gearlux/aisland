"""Service supervision via process-compose.

aisland delegates process *supervision* (start/stop/status, readiness probes,
crash recovery, log capture) to `process-compose
<https://github.com/F1bonacc1/process-compose>`_ — a single-binary,
native-process orchestrator with docker-compose semantics. Each service class
keeps its domain logic (downloads, config generation, ``.env`` publication)
and hands the assembled command line to the supervisor instead of spawning it
directly.

Desired-state model (verified empirically against process-compose v1.116.0):

* The generated ``aisland/data/process-compose.yaml`` is the single
  desired-state document — ``disabled: false`` means "should be running".
* Starting a service rewrites its entry (command/env/probe), enables it, and
  applies the config: a live ``project update`` when the server is already up
  (which auto-starts newly-enabled and stops newly-disabled processes), or
  ``up --detached`` otherwise.
* Stopping a service disables its entry and re-applies — never a bare
  ``process stop``, so a later update cannot resurrect it.

The server listens on a unix socket inside ``aisland/data/`` (TCP on Windows,
where unix sockets are unavailable — port via ``AISLAND_SUPERVISOR_PORT``), so
multiple workspace checkouts never collide and no TCP port is consumed on
Unix.
"""

import json
import os
import platform
import re
import shlex
import shutil
import sqlite3
import subprocess
from contextlib import closing
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import click
import yaml

from aisland import locations

# Mirrors manager.py's path constants. Kept local (not imported) because
# manager imports this module for BaseService — importing manager back at
# module level would be a circular import.
BASE_DIR = locations.state_dir()
DATA_DIR = BASE_DIR / "data"
BIN_DIR = BASE_DIR / "bin"

CONFIG_FILE = DATA_DIR / "process-compose.yaml"
SOCKET_PATH = DATA_DIR / "process-compose.sock"
SERVER_LOG = DATA_DIR / "process-compose.log"

# TCP fallback for Windows, where unix domain sockets are not supported by
# process-compose. Documented in the workspace .env.
DEFAULT_TCP_PORT = 9089

# Header prepended to the generated config (Generator Provenance mandate).
_PROVENANCE_HEADER = """\
# =========================================================================
# AUTO-GENERATED FILE — DO NOT EDIT BY HAND
# Generated by: aisland <service> start/stop (desired-state document)
# Source template: aisland/supervisor.py (register_process/save_config)
# To regenerate:  start or stop any aisland service
# =========================================================================
"""

_CLIENT_TIMEOUT = 30  # seconds; every client call is a local RPC

# macOS Full Disk Access pre-flight ------------------------------------------
#
# macOS TCC attributes a daemon tree's file access to the tree's ROOT process.
# For every supervised service that root is the process-compose server itself,
# so when workspace data lives on an external volume (/Volumes/...) the
# SUPERVISOR binary must hold the Full Disk Access grant — grants held by
# java/python further down the tree are ignored, and the denial surfaces as a
# misleading `PermissionError: [Errno 1] Operation not permitted` deep inside
# the service (canonical case: huggingface_hub cache reads during a Jenkins
# notebook build, while the same command works from an interactive shell).
# Grants are recorded against the resolved (versioned Cellar) binary path, so
# every process-compose upgrade silently orphans the grant — the formula is
# `brew pin`ned to make upgrades deliberate, and this pre-flight catches the
# drift at server start. See aisland/README.md § "macOS: Full Disk Access".
_TCC_SYSTEM_DB = Path("/Library/Application Support/com.apple.TCC/TCC.db")
_TCC_FDA_SERVICE = "kTCCServiceSystemPolicyAllFiles"
# Workspace .env keys that commonly point at an external volume; any of them
# under /Volumes/ makes the grant a requirement for supervised services.
_TCC_PROTECTED_ENV_KEYS = ("DATA_ROOT", "MODEL_ROOT", "HF_HOME")


def find_binary() -> Optional[str]:
    """Locate the process-compose binary: PATH first, then aisland/bin."""
    found = shutil.which("process-compose")
    if found:
        return found
    vendored = BIN_DIR / "process-compose"
    if vendored.exists():
        return str(vendored)
    return None


def ensure_binary() -> str:
    """Return the process-compose binary path, installing it if missing.

    macOS installs via Homebrew (the ``f1bonacc1/tap`` tap — also declared in
    aisland's ``[tool.aisland.sys-dependencies]`` so ``aisland setup`` /
    ``setup.sh`` provision it up front); Linux installs the upstream release
    binary into ``aisland/bin`` via the userspace-tools registry.
    """
    binary = find_binary()
    if binary:
        return binary

    # Circular-dependency exception to the top-level-imports mandate:
    # manager.py imports this module (BaseService delegates to it), so the
    # installer helpers must be imported lazily here.
    import platform

    from aisland.manager import _install_brew_packages, _install_userspace_tool

    click.echo("process-compose not found — installing...")
    system = platform.system()
    if system == "Darwin":
        _install_brew_packages({"f1bonacc1/tap/process-compose"})
    elif system == "Linux":
        _install_userspace_tool("process-compose")
    binary = find_binary()
    if binary is None:
        raise click.ClickException(
            "process-compose is required to manage aisland services and could not be installed. "
            "Install it manually (https://github.com/F1bonacc1/process-compose) or re-run 'aisland setup'."
        )
    return binary


def _connection_args() -> List[str]:
    """Client/server connection flags: unix socket on Unix, TCP on Windows."""
    if os.name == "nt":
        port = int(os.environ.get("AISLAND_SUPERVISOR_PORT", str(DEFAULT_TCP_PORT)))
        return ["--port", str(port)]
    return ["--use-uds", "--unix-socket", str(SOCKET_PATH)]


def _run_client(
    args: List[str], capture: bool = True, env: Optional[Dict[str, str]] = None
) -> subprocess.CompletedProcess:
    """Run a process-compose client command against the aisland server."""
    binary = ensure_binary()
    cmd = [binary, *args, *_connection_args()]
    return subprocess.run(
        cmd,
        capture_output=capture,
        text=True,
        check=False,
        timeout=_CLIENT_TIMEOUT,
        env=env,
    )


def read_workspace_env(workspace_root: Optional[Path] = None) -> Dict[str, str]:
    """``KEY=VALUE`` pairs from the workspace ``.env`` (best-effort, verbatim).

    Comments and malformed lines are skipped; values are NOT interpolated.
    Used both by services that publish/consume workspace configuration (e.g.
    Label Studio credentials) and by :func:`apply` for ``${VAR}`` expansion —
    see the comment there. ``workspace_root`` defaults to the discovered root.
    """
    env_file = (workspace_root or _workspace_root()) / ".env"
    if not env_file.exists():
        return {}
    out: Dict[str, str] = {}
    for line in env_file.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        out[key.strip()] = value.strip()
    return out


def write_workspace_env(values: Dict[str, str]) -> Path:
    """Set each ``KEY=VALUE`` in the workspace ``.env``, replacing an existing key IN PLACE.

    The counterpart of :func:`read_workspace_env`, for services that publish what they
    decided (a served directory, a URL) so a config or a later start can read it back as
    ``$KEY``. Neighbouring lines — comments included — are left untouched; a key not yet
    present is appended. Values are written verbatim (no quoting, no interpolation).
    """
    env_file = _workspace_root() / ".env"
    lines = env_file.read_text().splitlines() if env_file.exists() else []
    for key, value in values.items():
        entry = f"{key}={value}"
        for index, existing in enumerate(lines):
            if existing.strip().startswith(f"{key}="):
                lines[index] = entry
                break
        else:
            lines.append(entry)
    env_file.write_text("\n".join(lines) + "\n")
    return env_file


def is_server_running() -> bool:
    """True if the aisland process-compose server answers on its socket."""
    if find_binary() is None:
        return False
    if os.name != "nt" and not SOCKET_PATH.exists():
        return False
    result = _run_client(["project", "state"])
    return result.returncode == 0


def load_config() -> Dict[str, Any]:
    """Read the desired-state document (empty skeleton if absent/corrupt)."""
    if CONFIG_FILE.exists():
        try:
            data = yaml.safe_load(CONFIG_FILE.read_text())
            if isinstance(data, dict) and isinstance(data.get("processes"), dict):
                return data
        except yaml.YAMLError as e:
            click.echo(f"  - Warning: {CONFIG_FILE} is unreadable ({e}); regenerating.")
    return {"version": "0.5", "processes": {}}


def save_config(config: Dict[str, Any]) -> None:
    """Write the desired-state document with its provenance header."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(config, sort_keys=True, default_flow_style=False)
    CONFIG_FILE.write_text(_PROVENANCE_HEADER + body)


def register_process(
    name: str,
    command: List[str],
    env: Optional[Dict[str, str]] = None,
    log_file: Optional[Path] = None,
    readiness: Optional[Dict[str, Any]] = None,
    enabled: bool = True,
) -> None:
    """Create or replace a process entry in the desired-state document.

    Args:
        name: Process name (the aisland service name).
        command: argv list; joined with shell quoting.
        env: Extra environment variables for the process (added on top of the
            server's inherited environment).
        log_file: Per-process log destination (``log_location``).
        readiness: Optional HTTP readiness probe: ``{"port": int, "path": str}``.
        enabled: Desired state — False registers the entry without starting it.
    """
    config = load_config()
    entry: Dict[str, Any] = {
        "command": shlex.join(command),
        "working_dir": str(_workspace_root()),
        "disabled": not enabled,
        # Crash recovery: restart on failure only — a manual stop (a disable
        # via project update) is respected and never counts as a failure.
        "availability": {"restart": "on_failure", "max_restarts": 3},
        "shutdown": {"signal": 15, "timeout_seconds": 15},
    }
    if log_file is not None:
        entry["log_location"] = str(log_file)
    if env:
        entry["environment"] = [f"{key}={value}" for key, value in sorted(env.items())]
    if readiness is not None:
        entry["readiness_probe"] = {
            "http_get": {
                "host": "127.0.0.1",
                "port": readiness["port"],
                "path": readiness.get("path", "/"),
            },
            "initial_delay_seconds": 2,
            "period_seconds": 3,
            # Generous: readiness is informational (shown in status); slow
            # cold starts (Jenkins plugin scans) must eventually flip Ready.
            "failure_threshold": 60,
        }
    config["processes"][name] = entry
    save_config(config)


def set_enabled(name: str, enabled: bool) -> bool:
    """Flip the desired state of a registered process. False if unknown."""
    config = load_config()
    entry = config["processes"].get(name)
    if entry is None:
        return False
    entry["disabled"] = not enabled
    save_config(config)
    return True


def get_registered_port(name: str) -> Optional[int]:
    """Return the readiness-probe port recorded for a process, if any."""
    entry = load_config()["processes"].get(name, {})
    port = entry.get("readiness_probe", {}).get("http_get", {}).get("port")
    return int(port) if port is not None else None


def remove_process(name: str) -> bool:
    """Drop a process from the desired-state document. False if unknown."""
    config = load_config()
    if name not in config["processes"]:
        return False
    del config["processes"][name]
    save_config(config)
    return True


def apply() -> None:
    """Make the running state match the desired-state document.

    Live server → ``project update`` (starts newly-enabled processes, stops
    newly-disabled ones). No server → start one detached, but only when at
    least one process is enabled (an all-disabled document needs no server).

    ``${VAR}`` references in the desired-state document (e.g. Label Studio's
    credential entries — kept as references so no secret value lands in the
    generated YAML) are expanded CLIENT-side when the config is loaded, from
    the environment of the process running ``project update`` — NOT from the
    server's environment (which loaded ``.env`` once at startup and never
    re-reads it). The workspace ``.env`` is therefore layered over
    ``os.environ`` for every update; without this, an apply from a shell that
    never sourced ``project.bashrc`` would expand the references to empty
    strings and silently wipe the stored values. (Verified empirically
    against process-compose v1.116.0.) Corollary: a literal ``$`` in any
    document value would be expanded here — don't put one in.
    """
    if is_server_running():
        result = _run_client(
            ["project", "update", "-f", str(CONFIG_FILE)],
            env={**os.environ, **read_workspace_env()},
        )
        if result.returncode != 0:
            raise click.ClickException(
                f"process-compose config update failed: {result.stderr.strip() or result.stdout.strip()}"
            )
        return

    config = load_config()
    if not any(not p.get("disabled", False) for p in config["processes"].values()):
        return
    _start_server()


def _tcc_full_disk_access_granted(binary: Path) -> Optional[bool]:
    """Whether the system TCC database grants ``binary`` Full Disk Access.

    Returns None when the database cannot be read — the invoking shell may
    itself lack Full Disk Access, and an inconclusive probe must never warn.
    Both the given path and its resolved target are checked because System
    Settings records the resolved Cellar path while PATH holds the Homebrew
    symlink.
    """
    try:
        with closing(sqlite3.connect(f"file:{_TCC_SYSTEM_DB}?mode=ro", uri=True, timeout=1.0)) as db:
            rows = db.execute(
                "SELECT auth_value FROM access WHERE service = ? AND client IN (?, ?)",
                (_TCC_FDA_SERVICE, str(binary), str(binary.resolve())),
            ).fetchall()
    except sqlite3.Error:
        return None
    # auth_value: 0 = denied, 1 = unknown, 2 = allowed, 3 = limited.
    return any(row[0] is not None and row[0] >= 2 for row in rows)


def _preflight_full_disk_access() -> None:
    """Warn at server start when the supervisor binary lacks Full Disk Access.

    Fires only when a workspace data path points at an external volume AND
    the TCC database is readable AND the grant is definitively absent. Warns
    (with the exact path to grant) instead of failing — services that never
    touch the volume still work without the grant.
    """
    if platform.system() != "Darwin":
        return
    env = {**read_workspace_env(), **os.environ}
    exposed = {key: value for key in _TCC_PROTECTED_ENV_KEYS if (value := env.get(key, "")).startswith("/Volumes/")}
    if not exposed:
        return
    binary = Path(ensure_binary())
    if _tcc_full_disk_access_granted(binary) is not False:
        return
    keys = ", ".join(f"{key}={value}" for key, value in sorted(exposed.items()))
    click.echo(
        click.style("WARNING: the supervisor binary has no macOS Full Disk Access grant.", fg="yellow", bold=True),
        err=True,
    )
    click.echo(
        f"  {keys} point(s) at an external volume, but macOS attributes every supervised\n"
        "  service's file access to the process-compose binary (the daemon-tree root), so\n"
        "  Jenkins builds etc. will fail there with 'Operation not permitted'.\n"
        "  Fix: System Settings > Privacy & Security > Full Disk Access > + >\n"
        f"       {binary.resolve()}\n"
        "  then restart the supervisor: aisland supervisor down && aisland start --background\n"
        "  (Re-grant after every process-compose upgrade — the grant pins to the versioned\n"
        "  path, which is why the formula is kept `brew pin`ned.)",
        err=True,
    )


def _start_server() -> None:
    """Start the detached process-compose server for the aisland project."""
    _preflight_full_disk_access()
    binary = ensure_binary()
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    cmd = [
        binary,
        "up",
        "-f",
        str(CONFIG_FILE),
        "--detached",
        # Keep the server alive when every process is stopped — service
        # start/stop must not tear the supervisor down between commands.
        "--keep-project",
        "--log-file",
        str(SERVER_LOG),
        *_connection_args(),
    ]
    # cwd = workspace root so process-compose's default `.env` loading picks
    # up the workspace .env (DATA_ROOT, LABELSTUDIO_*, ...), mirroring
    # `source project.bashrc` for every supervised service.
    result = subprocess.run(
        cmd,
        cwd=_workspace_root(),
        capture_output=True,
        text=True,
        check=False,
        timeout=_CLIENT_TIMEOUT,
    )
    if result.returncode != 0:
        raise click.ClickException(
            f"failed to start the process-compose server: {result.stderr.strip() or result.stdout.strip()}"
        )


def list_processes() -> Dict[str, Dict[str, Any]]:
    """Return the server's process states keyed by name ({} if no server)."""
    if not is_server_running():
        return {}
    result = _run_client(["process", "list", "--output", "json"])
    if result.returncode != 0:
        return {}
    try:
        processes = json.loads(result.stdout)
    except json.JSONDecodeError:
        return {}
    return {proc["name"]: proc for proc in processes if isinstance(proc, dict) and "name" in proc}


def get_process(name: str) -> Optional[Dict[str, Any]]:
    """Return one process's state dict, or None if unknown / no server."""
    return list_processes().get(name)


def get_ports(name: str) -> List[int]:
    """Return the TCP ports a supervised process is listening on (best-effort)."""
    if not is_server_running():
        return []
    result = _run_client(["process", "ports", name])
    # Output shape (v1.116.0): "Process <name> TCP ports: [9080 9081]".
    match = re.search(r"\[([0-9,\s]*)\]", result.stdout + result.stderr)
    if not match:
        return []
    # One entry per listening socket — a multi-worker server (e.g. gunicorn)
    # repeats the same port, so dedupe.
    return sorted({int(p) for p in re.findall(r"\d+", match.group(1))})


def restart_process(name: str) -> bool:
    """Restart a supervised process in place."""
    result = _run_client(["process", "restart", name])
    return result.returncode == 0


def start_process(name: str) -> bool:
    """Explicitly start an enabled-but-not-running process.

    Needed when ``project update`` is a no-op: re-starting a service whose
    previous run exhausted its restarts leaves the config byte-identical, so
    the update alone does not relaunch it.
    """
    result = _run_client(["process", "start", name])
    return result.returncode == 0


def follow_logs(name: str, tail: int = 10) -> None:
    """Stream a process's logs to the terminal until interrupted (Ctrl+C)."""
    binary = ensure_binary()
    cmd = [binary, "process", "logs", name, "--follow", "--tail", str(tail), *_connection_args()]
    # Inherit stdio so the stream lands on the user's terminal directly.
    # KeyboardInterrupt propagates to the caller, which decides whether the
    # interrupt should also stop the service (foreground-start semantics).
    subprocess.run(cmd, check=False)


def shutdown_server() -> None:
    """Stop every supervised process and terminate the supervisor itself."""
    if not is_server_running():
        click.echo("Supervisor (process-compose) is not running.")
        return
    result = _run_client(["down"])
    if result.returncode == 0:
        click.echo("Supervisor (process-compose) stopped.")
    else:
        click.echo(f"Error stopping supervisor: {result.stderr.strip()}", err=True)


def attach() -> None:
    """Attach the process-compose TUI to the running aisland server."""
    if not is_server_running():
        click.echo("Supervisor (process-compose) is not running. Start a service first.")
        return
    binary = ensure_binary()
    subprocess.run([binary, "attach", *_connection_args()], check=False)


def print_status() -> None:
    """Print the supervisor state and its process table (for the CLI)."""
    if not is_server_running():
        click.echo(f"  Supervisor      : {click.style('Stopped', fg='red')} (process-compose)")
        return
    click.echo(f"  Supervisor      : {click.style('Running', fg='green')} (process-compose)")
    click.echo(f"    Config        : {CONFIG_FILE}")
    click.echo(f"    Server log    : {SERVER_LOG}")
    for name, proc in sorted(list_processes().items()):
        status = proc.get("status", "?")
        ready = proc.get("is_ready", "-")
        color = "green" if proc.get("is_running") else "red"
        detail = f"(PID: {proc.get('pid')}, ready: {ready})" if proc.get("is_running") else ""
        click.echo(f"    {name:<13} : {click.style(status, fg=color)} {detail}")


def wait_for(name: str, running: bool, timeout: float = 30.0) -> Optional[Dict[str, Any]]:
    """Poll until the process's is_running matches ``running`` (or timeout).

    Returns the final state dict (None if the process never appeared). This
    is a deliberate poll against the supervisor's API — the supervisor owns
    the process lifecycle, so there is no aisland-side event to join on.
    """
    import time

    deadline = time.monotonic() + timeout
    state: Optional[Dict[str, Any]] = None
    while time.monotonic() < deadline:
        state = get_process(name)
        if state is not None and bool(state.get("is_running")) == running:
            return state
        time.sleep(0.5)
    return state


def wait_for_outcome(name: str, timeout: float = 45.0) -> Tuple[str, Optional[Dict[str, Any]]]:
    """Wait for a just-started process to reach a definite startup outcome.

    A momentary ``is_running`` is NOT success — a crash-looping process (e.g.
    a port conflict) flips is_running on and off through its restart cycle
    before the supervisor gives up. Outcomes:

    * ``"ready"``   — the readiness probe passed; the service answers HTTP.
    * ``"running"`` — no probe configured, and the process survived its first
      seconds without exiting.
    * ``"failed"``  — the process exited and the supervisor gave up
      (status ``Completed``/``Error`` with a non-zero exit code).
    * ``"pending"`` — still running at the timeout but the probe has not
      passed yet (long cold starts, e.g. Jenkins' first plugin scan).
    """
    import time

    deadline = time.monotonic() + timeout
    stable_polls = 0
    state: Optional[Dict[str, Any]] = None
    while time.monotonic() < deadline:
        state = get_process(name)
        if state is not None:
            if state.get("is_ready") == "Ready":
                return "ready", state
            if not state.get("is_running") and state.get("status") in ("Completed", "Error"):
                return "failed", state
            if state.get("is_running") and not state.get("has_ready_probe"):
                # No probe to consult: surviving ~2s of polls is the best
                # available "it came up" signal.
                stable_polls += 1
                if stable_polls >= 4:
                    return "running", state
        time.sleep(0.5)
    if state is not None and state.get("is_running"):
        return "pending", state
    return "failed", state


def port_in_use(port: int) -> Optional[int]:
    """Return the PID listening on ``port`` (best-effort; -1 if unknown owner).

    Used as a pre-start check: a service whose port is already taken would
    otherwise crash-loop through its restart budget with a log-only error —
    most commonly an orphan instance started by a pre-supervisor aisland.
    Returns None when the port is free.
    """
    import socket

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.5)
        if sock.connect_ex(("127.0.0.1", port)) != 0:
            return None
    # Something answers — identify it if the platform lets us (diagnostic only).
    try:
        out = subprocess.check_output(
            ["lsof", "-nP", f"-iTCP:{port}", "-sTCP:LISTEN", "-t"],
            text=True,
            stderr=subprocess.DEVNULL,
            timeout=5,
        ).strip()
        return int(out.splitlines()[0])
    except (subprocess.SubprocessError, FileNotFoundError, ValueError, IndexError, OSError):
        return -1


def _workspace_root() -> Path:
    """Workspace root via manager's marker search (lazy import — see above)."""
    from aisland.manager import get_workspace_root

    return get_workspace_root()
