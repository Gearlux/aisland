def _emit_key(name: str) -> str:
    """A TOML key, quoted only when it is not a bare key (project names rarely need it)."""
    return name if _BARE_KEY.fullmatch(name) else '"' + name.replace('"', '\\"') + '"'


def _emit_value(value: Any) -> Optional[str]:
    """One TOML scalar or flat list, or ``None`` when the type has no rendering here.

    Hand-emitted rather than via ``tomli-w``: the schema is strings, string lists and tables
    of strings, and aisland deliberately carries no TOML-writer dependency (the same reasoning
    as :func:`aisland.manager._emit_uv_toml`, which this mirrors).
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, list):
        items = [_emit_value(item) for item in value]
        if any(item is None for item in items):
            return None
        return "[" + ", ".join(item for item in items if item is not None) + "]"
    return None


def _emit_table(prefix: str, table: Dict[str, Any], lines: List[str]) -> None:
    """Emit ``[prefix]`` and, recursively, its sub-tables (``[sources.confluid]``).

    A table holding ONLY sub-tables emits no header of its own — ``[sources]`` above
    ``[sources.confluid]`` would be noise, and TOML does not need it.
    """
    scalars = {k: v for k, v in table.items() if not isinstance(v, dict)}
    subs = {k: v for k, v in table.items() if isinstance(v, dict)}
    if scalars or not subs:
        lines.append(f"[{prefix}]")
        for key, value in scalars.items():
            rendered = _emit_value(value)
            if rendered is None:
                click.echo(f"  - Warning: skipping {prefix}.{key} (unsupported type {type(value).__name__})")
                continue
            lines.append(f"{_emit_key(key)} = {rendered}")
        lines.append("")
    for name in sorted(subs):
        _emit_table(f"{prefix}.{_emit_key(name)}", subs[name], lines)


def _ordered(keys: List[str]) -> List[str]:
    """Known keys in :data:`_KEY_ORDER`, then anything else alphabetically."""
    known = [key for key in _KEY_ORDER if key in keys]
    return known + sorted(key for key in keys if key not in _KEY_ORDER)


def render(data: Dict[str, Any]) -> str:
    """The full file: provenance header, then each section behind its own comment block.

    Scalars and lists are emitted before any table because TOML binds a bare key to the most
    recent table header — ``frameworks = [...]`` written after ``[sources.confluid]`` would
    silently become ``sources.confluid.frameworks``.
    """
    lines: List[str] = [_HEADER]
    scalars = _ordered([key for key, value in data.items() if not isinstance(value, dict)])
    tables = _ordered([key for key, value in data.items() if isinstance(value, dict)])

    for key in scalars:
        rendered = _emit_value(data[key])
        if rendered is None:
            click.echo(f"  - Warning: skipping {key} (unsupported type {type(data[key]).__name__})")
            continue
        if key in _SECTION_DOC:
            lines.append(_SECTION_DOC[key])
        lines.append(f"{_emit_key(key)} = {rendered}")
        lines.append("")

    for key in tables:
        if not data[key]:
            continue
        if key in _SECTION_DOC:
            lines.append(_SECTION_DOC[key])
        _emit_table(_emit_key(key), data[key], lines)

    return "\n".join(lines).rstrip("\n") + "\n"
