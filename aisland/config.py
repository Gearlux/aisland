"""The workspace's ONE committed configuration file — ``<workspace>/config.toml``.

Three concerns each owned a file at the workspace root until 2026-08-01 (``sources.toml``,
``frameworks.toml``, ``trackers.toml``). They are the same KIND of thing — a committed,
shared decision whose per-machine deviation lives in ``.git/config`` and is never committed —
so they share one file, one provenance header, and one place to look::

    frameworks = ["torch", "lightning"]   # aisland framework set   (aisland/selection.py)
    trackers   = ["mlflow"]               # aisland tracker set     (aisland/selection.py)

    [mirrors.confluid]                    # aisland mirror set      (aisland/mirrors.py)
    url = "git@bitbucket.example.com:team/confluid.git"

This module owns the FILE — its layout, its documentation comments, reading it and rewriting
it. It deliberately owns none of the DATA: :mod:`aisland.selection` and :mod:`aisland.mirrors` convert their own domain types to and from plain TOML values and call :func:`update`. That is
why this module imports nothing from aisland, and therefore cannot participate in an import
cycle with any of its callers.

**The root ``uv.toml`` is NOT part of this file and cannot be.** uv reads its own ``uv.toml``
(or ``pyproject.toml``'s ``[tool.uv]``) and rejects a config file carrying anything else —
measured against uv 0.11.8::

    $ UV_CONFIG_FILE=config.toml uv pip install …
    error: Failed to parse: `config.toml`. The `sources` field is not allowed in a
    `uv.toml` file.

It is also generated + gitignored per machine (a private index reaches it only when its
project is activated), which this file is the opposite of. See
:func:`aisland.manager._write_root_uv_toml`.

Every write is WHOLE-FILE: :func:`update` loads the document, replaces ONE top-level key and
re-renders. That is what lets ``aisland tracker set`` leave the ``[mirrors.*]`` tables and the
``frameworks`` key intact while still emitting one consistently formatted file — the cost is
that a hand-edited file is normalised (and its own comments dropped) by the next command that
writes, which the header says up front.

An EMPTY document removes the file rather than leaving a header-only stub: for both selection
axes an absent key is what *unset* means (distinct from an empty list — see
:mod:`aisland.selection`), and a workspace that has configured nothing should not carry a
tracked file that says so.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path
from typing import Any, Dict, List, Optional

import click

#: The one committed configuration file, at the workspace root.
CONFIG_FILE = "config.toml"

#: The per-concern files this one replaced, mapped to the top-level key each became.
#: Read as a fallback (never written) so a checkout that predates the merge is not silently
#: read as "nothing is configured" — which for sources would quietly unmanage every project.
LEGACY_FILES: Dict[str, str] = {
    "frameworks": "frameworks.toml",
    "trackers": "trackers.toml",
    "sources": "sources.toml",
}

#: Legacy files whose WHOLE document is the value (``sources.toml`` was a table per project).
#: The selection files instead stored their value under a key of the same name.
_LEGACY_AT_ROOT = frozenset({"sources"})

#: Emission order for the keys this workspace knows about. TOML requires every top-level
#: scalar to precede the first table header, so the sections are emitted scalars-first
#: regardless; this only fixes the order WITHIN each group. Unknown keys follow, sorted.
_KEY_ORDER = ("frameworks", "trackers", "mirrors")

_HEADER = """\
# =========================================================================
# AUTO-GENERATED / MANAGED FILE — prefer the `aisland` commands over hand edits.
# Generated by: aisland framework set / aisland tracker set / aisland mirror set
# Source module: aisland/aisland/config.py (render)
# To inspect:    aisland config show
# =========================================================================
# The workspace's single COMMITTED configuration (shared between machines, and the only
# layer every generated CI pipeline reads). Each section has a command that maintains it;
# every command rewrites the WHOLE file, so hand-added comments do not survive one.
#
# Per-machine deviations are NEVER recorded here. They live in `.git/config` as
# `aisland.frameworks`, `aisland.trackers` and `aisland.mirror.<project>`, so one
# developer's local choice can never reach a tracked build file.
#
# NOT here: the workspace-root `uv.toml`. uv only reads a file of its own settings and
# rejects any foreign table, so that file stays separate — generated by `aisland setup`
# and gitignored, because it carries a private index only when its project is activated.
"""

_SECTION_DOC: Dict[str, str] = {
    "frameworks": """\
# --- frameworks: what this machine TRAINS WITH ---------------------------
# Each project installs the extras it declares under `[tool.aisland] frameworks` that
# appear here; a project declaring none is unaffected, and a name no project declares is
# inert. An ABSENT key means nobody has chosen yet (setup prompts); an empty list means
# "none, deliberately".
#   aisland framework list                   the declarations, the selection, the effect
#   aisland framework set torch keras        replace the selection and install it
#   aisland framework set --machine-only …   override on THIS machine only (.git/config)
#   aisland framework unset --machine-only   drop the override, fall back to this file""",
    "trackers": """\
# --- trackers: where results GO ------------------------------------------
# The sibling axis of `frameworks`, never merged with it: what a machine trains with and
# where its results go are unrelated choices, and folding them together would install a
# tracking client because someone picked a training engine. Declared per project under
# `[tool.aisland] trackers`.
#   aisland tracker list                     the declarations, the selection, the effect
#   aisland tracker set mlflow aim           replace the selection and install it
#   aisland tracker set --machine-only …     override on THIS machine only (.git/config)
#   aisland tracker unset --machine-only     drop the override, fall back to this file""",
    "mirrors": """\
# --- mirrors: a second host each project is copied to --------------------
# The primary stays the `.gitmodules` remote (pulled from, pushed to). The mirror only
# receives: a sync pushes the primary's dev/main, main and tags, fast-forward only, never
# forcing, never deleting, never overwriting a tag. Kept as the remote `mirror` in the checkout.
#   url = the mirror's git remote (ssh or https).
#   aisland mirror list                      per project: committed, override, what a sync would push
#   aisland mirror set loggair <url>         record a mirror and add the remote
#   aisland mirror sync [loggair]            push to the mirror(s); /push-all and /ship run it
#   aisland mirror unset loggair             drop the mirror and the remote""",
}

#: A bare TOML key needs no quoting when it is made only of these characters.
_BARE_KEY = re.compile(r"[A-Za-z0-9_-]+")

#: Paths already reported as legacy, so a warning is emitted once per file per process
#: rather than on every read (``load`` runs several times in a single command).
_warned: set = set()


def config_path(workspace_root: Path) -> Path:
    """Absolute path of the workspace's ``config.toml`` (whether or not it exists)."""
    return workspace_root / CONFIG_FILE


def _parse(path: Path) -> Dict[str, Any]:
    """Parse one TOML file; a missing or malformed file yields ``{}`` with a warning.

    Never raises: every caller runs inside ``aisland setup`` or a CI scaffold, and a broken
    config must degrade to "nothing is configured" rather than abort a provisioning run.
    """
    if not path.exists():
        return {}
    try:
        return tomllib.loads(path.read_text())
    except (OSError, tomllib.TOMLDecodeError) as exc:
        click.echo(f"  - Warning: could not read {path}: {exc}")
        return {}


def load(workspace_root: Path) -> Dict[str, Any]:
    """The whole configuration document, with any legacy per-concern file folded in.

    The fallback is read-only and per KEY: a legacy file is consulted only for a key
    ``config.toml`` does not already carry, so a migrated section can never be resurrected by
    a stale file. It exists because the alternative failure is silent — a checkout predating
    the merge would read as "no sources configured", i.e. every project unmanaged.

    Writing anything (:func:`update`) completes the migration and deletes the legacy files.
    """
    data = _parse(config_path(workspace_root))
    for key, filename in LEGACY_FILES.items():
        if key in data:
            continue
        path = workspace_root / filename
        if not path.exists():
            continue
        legacy = _parse(path)
        value = legacy if key in _LEGACY_AT_ROOT else legacy.get(key)
        if value is None:
            continue
        data[key] = value
        if str(path) not in _warned:
            _warned.add(str(path))
            click.echo(
                f"  - Note: reading legacy {filename}; run `aisland config migrate` to fold it into {CONFIG_FILE}."
            )
    return data


def update(workspace_root: Path, key: str, value: Optional[Any]) -> Path:
    """Set (or, with ``value=None``, remove) ONE top-level key, preserving every other section.

    Load-modify-rewrite rather than a surgical edit: the file is small, fully managed, and the
    alternative (splicing text) would have to understand the comments it must not disturb.
    Returns the config path — which may no longer exist, when the last section was removed.
    """
    data = load(workspace_root)
    if value is None:
        data.pop(key, None)
    else:
        data[key] = value
    return write(workspace_root, data)


def write(workspace_root: Path, data: Dict[str, Any]) -> Path:
    """Render ``data`` to ``config.toml``, then retire any legacy file it now supersedes.

    An empty document removes the file instead of writing a header-only stub (see the module
    docstring). Legacy files are dropped on every write, not only on an explicit migration:
    once a write has happened, ``config.toml`` is authoritative for that key and a lingering
    ``frameworks.toml`` could only ever mislead a reader.
    """
    path = config_path(workspace_root)
    if any(value not in (None, {}) for value in data.values()):
        path.write_text(render(data))
    else:
        path.unlink(missing_ok=True)
    _retire_legacy(workspace_root)
    return path


def _retire_legacy(workspace_root: Path) -> None:
    """Delete the per-concern files ``config.toml`` replaced, reporting each once."""
    for filename in LEGACY_FILES.values():
        path = workspace_root / filename
        if path.exists():
            path.unlink()
            click.echo(f"  - Migrated {filename} into {CONFIG_FILE} (removed the legacy file).")


def migrate(workspace_root: Path) -> List[str]:
    """Fold every legacy per-concern file into ``config.toml``. Returns the names folded.

    Idempotent and cheap enough to call from ``aisland setup``: with no legacy file present it
    touches nothing at all — deliberately, so a routine setup never rewrites (and reformats) a
    config file that no command asked to change.
    """
    present = [name for name in LEGACY_FILES.values() if (workspace_root / name).exists()]
    if not present:
        return []
    write(workspace_root, load(workspace_root))
    return present


