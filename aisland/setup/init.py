"""``aisland workspace init <folder>``: a new workspace, from nothing or from a ``workspace.toml``.

A workspace, as aisland sees it, is a git repository whose projects are folders holding a ``pyproject.toml`` —
usually submodules. ``aisland setup`` then needs a ``.venv`` at the root and reads, when they exist,
``workspace.toml`` (its projects and their settings, kept current by setup: :mod:`aisland.workspace.file`),
``.env`` (exported by ``project.bashrc``) and ``mypy.ini`` (its ``mypy_path`` kept complete).
``init`` writes the starting files, runs ``git init``, adds each project of a ``--from`` file and each ``--add``
repository as a submodule, then each clone already in the folder (:func:`aisland.workspace.clones.found`: a subfolder
with a ``.git`` folder, an ``origin`` and a ``pyproject.toml``) as it is — its checkout, branch and edits kept —,
writes ``workspace.toml`` and installs the workspace git aliases. It works the same
whichever way aisland is installed; the workspace it makes is one that aisland from a wheel works in
(:mod:`aisland.locations`).

In a folder that already is a git repository it sets that one up instead: no ``git init``,
the ``--add`` projects added, the starting files that are missing written, the aliases and the agent harness
installed. A ``--from`` file is refused there (the repository keeps its own ``workspace.toml``), and so is ``--local``.

It never writes over a file that exists. A ``--from`` file that cannot be read is refused before anything is written,
naming the file and the line; the file it reads is copied in as the new workspace's ``workspace.toml``. The one
exception is ``--rewrite <file>``: each starting file it names is written again from the template, the old copy kept
as ``<file>.bak``; in an existing repository that is all init does, and it is refused beside any other option.

Two choices of the root's, each its own flag: ``--local`` makes a new root repository that tracks only the projects
(:mod:`aisland.workspace.local`: its ``.gitignore`` ignores everything, ``.gitmodules`` and the projects are its first
commit), and ``--untracked`` makes the root record none of its projects' commits (:mod:`aisland.workspace.tracking`).

A folder holding the workspace's root project (:mod:`aisland.workspace.root_project`) is set up otherwise: init makes
it a root repository that records no project — git's workspace aliases and an editor's worktrees need a repository at
the root, and ``workspace.toml`` stays the one list of the projects. Every file is ignored (``.git/info/exclude``), no
submodule is added and the clones stay plain clones; ``--add``, ``--from``, ``--local`` and ``--rewrite``, which would
add submodules or files beside the root project, are refused there.
"""

