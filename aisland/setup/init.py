#: The files ``init`` starts a workspace with, in the order it writes them; ``--rewrite`` takes only these.
StartingFile = Literal[".gitignore", ".env", "mypy.ini", "vscode-init-bash.sh"]
STARTING_FILES: Tuple[StartingFile, ...] = get_args(StartingFile)

#: The terminal init the editor file's profile runs (`${workspaceFolder:<name>}/vscode-init-bash.sh`).
VSCODE_INIT_BASH = locations.PACKAGE_DIR / "templates" / "vscode-init-bash.sh"

_HEADER = """\
# =========================================================================
# Written by: aisland workspace init (aisland/aisland/setup/init.py)
# A starting point that is yours to edit. Written over only on request: aisland workspace init . --rewrite <file>
# =========================================================================
"""

#: What `aisland setup` and aisland's state write into the root, per machine — never committed.
_GITIGNORE = (
    _HEADER
    + """
# aisland's state when it runs from a wheel: services' data, vendored tools (aisland.locations).
.aisland/
# The workspace venv (a folder, or a link to a venv kept elsewhere) and this machine's environment
# (exported by project.bashrc).
.venv
.env
# Generated by `aisland setup` / `aisland completion install`, per machine.
/env.complete
/env.example
/project.bashrc
/pyrightconfig.json
/uv.toml
/.mcp.json
/.gemini/settings.json
/*.code-workspace
.project.bashrc.completion
user.bashrc
__pycache__/
"""
)

#: A local workspace's ``.gitignore`` (``init --local``): the root tracks only ``.gitmodules`` and the submodules.
_LOCAL_GITIGNORE = (
    _HEADER
    + """
# A local workspace (aisland workspace init --local): this root repository tracks only the projects —
# .gitmodules and the submodules — so everything else here is this machine's. Add a project with
# `git submodule add -f <url>` (the -f because of the line below), then `aisland setup`.
/*
"""
)

_ENV = (
    _HEADER
    + """
# This machine's environment, exported by `source project.bashrc`; never committed (.gitignore).
# Configs read these through `$VAR` substitution. Uncomment and set the ones this workspace uses:
# DATA_ROOT=/path/to/datasets
# MODEL_ROOT=/path/to/models
# RUN_DIR=/path/to/runs
"""
)


def _mypy_ini(folders: Sequence[str]) -> str:
    return (
        (
            _HEADER
            + """
[mypy]
# The folders mypy searches for the workspace's packages; `aisland setup` adds each project it finds.
# Run mypy from the workspace root against a project folder: mypy <project>/
mypy_path = """
            + ":".join(folders)
        ).rstrip()
        + "\n"
    )


def _row(name: str, what: str) -> str:
    """A report line: the name in a column of 26, always a space before what is said of it."""
    return f"    {name.ljust(25)} {what}"


#: A line git writes while it clones that is progress, not what went wrong: left out of a failed clone's message.
_GIT_PROGRESS = re.compile(r"^(remote: |Cloning into |[A-Z][a-z]+( [a-z]+)*: +\d+% )")
#: Back to the start of the terminal's line and erase it: git's progress is drawn over its previous line.
_REDRAW = "\r\x1b[K"
#: The indent of a line below a project's ``[N/M]`` line.
_INDENT = "      "


def _say(text: str) -> None:
    """A progress line. It goes to stderr, so stdout holds the report alone (``init … > report.txt``)."""
    console.echo(text, err=True)


def _add_submodule(
    root: Path, url: str, path: Optional[str] = None, branch: Optional[str] = None, step: str = ""
) -> None:
    """``git submodule add`` ``url``. On a terminal git's download progress is drawn on one line, each of its lines
    over the last, and erased when the clone ends; elsewhere (a pipe, a log) git is asked for none.

    A refusal raises naming ``step`` (``[2/5] models``) and git's message without its progress lines."""
    terminal = sys.stderr.isatty()
    args = [
        "git",
        *gitcmd.network_options(),  # a remote that stops sending is given up, as every git network call is
        "submodule",
        "add",
        "-q",
        *(["--progress"] if terminal else []),
        *(["-b", branch] if branch else []),
        "--",  # a url or path from a file is never read as an option
        url,
        *([path] if path else []),
    ]
    process = subprocess.Popen(
        args,
        cwd=root,
        env=gitcmd.network_env(),  # no credential prompt: git asks on the terminal, whatever stdin is
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE,
    )
    assert process.stderr is not None  # stderr=PIPE
    # A line wider than the terminal wraps, and the carriage return then goes back to its last row only.
    width = shutil.get_terminal_size().columns - len(_INDENT) - 1
    decoder = codecs.getincrementaldecoder("utf-8")(errors="replace")
    said: List[str] = []
    pending = ""
    while chunk := os.read(process.stderr.fileno(), 4096):
        # git ends a progress line with a carriage return and every other line with a newline.
        *ended, pending = re.split(r"[\r\n]", pending + decoder.decode(chunk))
        for line in (text.strip() for text in ended):
            if not line:
                continue
            said.append(line)
            if terminal:
                console.echo(f"{_REDRAW}{_INDENT}{line[:width]}", err=True, nl=False)
    if pending.strip():
        said.append(pending.strip())
    if terminal and said:
        console.echo(_REDRAW, err=True, nl=False)
    if process.wait() != 0:
        message = "\n".join(line for line in said if not _GIT_PROGRESS.match(line)) or "\n".join(said)
        raise AislandError(f"{step}: could not add {url} as a submodule: {message}")


def runs_from_venv_of(root: Path) -> bool:
    """Whether this aisland runs from ``root``'s own ``.venv`` (a folder or a link to one): then it needs none made."""
    venv = venv_dir(root)
    return venv.exists() and Path(sys.prefix).resolve() == venv.resolve()


def _starting_files(root: Path) -> Dict[StartingFile, str]:
    """The text of each starting file for ``root``; ``mypy.ini`` lists the submodules holding a ``pyproject.toml``,
    and a local workspace's ``.gitignore`` ignores everything."""
    submodules = workspace_file.submodules(root)
    return {
        ".gitignore": _LOCAL_GITIGNORE if local_workspace.is_local(root) else _GITIGNORE,
        # A new .env starts as the projects' env.example (`aisland workspace env-example`), every line commented out.
        ".env": env_example.seed_text(root) or _ENV,
        "mypy.ini": _mypy_ini(
            [path for path, _url, _branch in submodules if (root / path / "pyproject.toml").is_file()]
        ),
        "vscode-init-bash.sh": VSCODE_INIT_BASH.read_text(),
    }


def _refuse_a_bak_in_the_way(root: Path, rewrite: Sequence[StartingFile]) -> None:
    """Before anything is written: a ``<file>.bak`` already there would be lost, so the whole run is refused."""
    for name in rewrite:
        bak = root / f"{name}.bak"
        if (root / name).exists() and bak.exists():
            raise AislandError(
                f"{bak} exists: move it away first, then rewrite {name} (its current copy is kept there)."
            )


def _write_starting_file(target: Path, text: str) -> None:
    """One starting file; ``.env``, which will hold the workspace's secrets, readable by its owner alone."""
    atomic.write_text(target, text, new_mode=atomic.PRIVATE if target.name == ".env" else None)


def _write_starting_files(root: Path, rewrite: Sequence[StartingFile], only_rewrite: bool = False) -> List[str]:
    """Write each starting file that is missing, and each of ``rewrite`` over its old copy (kept as ``.bak``).

    ``only_rewrite`` (an existing repository) writes the ``rewrite`` files alone, missing or not."""
    rows = []
    for name, text in _starting_files(root).items():
        if only_rewrite and name not in rewrite:
            continue
        target = root / name
        if target.exists():
            if name not in rewrite:
                rows.append(_row(name, "kept (it exists)"))
                continue
            target.rename(root / f"{name}.bak")
            _write_starting_file(target, text)
            rows.append(_row(name, f"rewritten (the old one kept as {name}.bak)"))
            continue
        _write_starting_file(target, text)
        rows.append(_row(name, "written"))
    return rows


def _clone(root: Path, plan: Sequence[Tuple[str, Optional[Tuple[str, Optional[str], Optional[str]]]]]) -> None:
    """Add each project of ``plan`` as a submodule, saying it as its clone starts (``[2/5] models  cloning …``) and
    ends (``done in 3.1 s``); a project left out (None) is said skipped and not counted."""
    total = sum(1 for _name, clone in plan if clone is not None)
    width = max((len(name) for name, _clone in plan), default=0)
    mark = len(f"[{total}/{total}]")
    number = 0
    for name, clone in plan:
        label = name.ljust(width)
        if clone is None:
            _say(f"{'[–]'.ljust(mark)} {label}  skipped (optional: aisland setup asks)")
            continue
        number += 1
        url, path, branch = clone
        step = f"[{number}/{total}]"
        _say(f"{step} {label}  cloning {url}" + (f" ({branch})" if branch else "") + " …")
        started = time.monotonic()
        _add_submodule(root, url, path, branch, step=f"{step} {name}")
        _say(f"{step} {label}  done in {time.monotonic() - started:.1f} s")


def _refuse_a_root_project(from_file: Path, listing: workspace_file.WorkspaceFile) -> None:
    """Refuse a file naming a root project, at its ``root`` line: such a workspace has no root repository, and init
    would make one of submodules. Such a workspace starts with the root project's clone and setup, as its how-to says.
    """
    root = workspace_file.root_row(listing)
    if root is None or root.url is None:  # a root project without a url: the plan below refuses its row
        return
    text = from_file.read_text(encoding="utf-8")
    header = table_line(text, "workspace")
    where = Where(from_file, key_line(text, header, locations.ROOT_KEY) if header else None)
    raise AislandError(
        f"{where}: the file names a root project ({root.name}), and init would make a root repository of submodules "
        "instead. In the folder for the workspace, clone it and run setup, as the file's first lines say:\n"
        f"  {workspace_file.clone_command(root)}\n"
        "  .venv/bin/aisland setup"
    )


def init_workspace(
    folder: Path,
    add: Sequence[str] = (),
    from_file: Optional[Path] = None,
    rewrite: Sequence[StartingFile] = (),
    local: bool = False,
    untracked: bool = False,
) -> None:
    """Make ``folder`` a new workspace (see the module docstring). Raises :class:`click.ClickException` on refusal.

    The projects of ``from_file`` (a ``workspace.toml``) are added first, in its order, each into its path on its
    branch, then each ``add``; the file is read before anything is written, so a file aisland refuses leaves the folder
    as it was, and it is copied in as the new workspace's ``workspace.toml``, which then lists the ``add`` ones too.
    Each of ``rewrite`` is written over its old copy, kept as ``<file>.bak``; in a folder that already is a git
    repository only those files are written. A folder that already is a repository is set up in place. ``local``
    makes the root track only the projects, ``untracked`` its projects' commits go unrecorded (the module docstring)."""
    listing = workspace_file.read(from_file) if from_file is not None else workspace_file.WorkspaceFile()
    if from_file is not None:
        _refuse_a_root_project(from_file, listing)
    listed = list(listing.projects.values())
    # Each project in the order init says it: its name and (url, path, branch), or None for one it leaves out.
    plan: List[Tuple[str, Optional[Tuple[str, Optional[str], Optional[str]]]]] = []
    for project in listed:
        if "active" in project.others:  # optional: `aisland setup` asks about it and checks it out if wanted
            plan.append((project.name, None))
            continue
        if project.url is None:  # the file reads one without (a source set before setup wrote it), init cannot clone it
            raise AislandError(f"{project.where}: project {project.name!r} has no url")
        plan.append((project.name, (project.url, project.path, project.branch)))
    plan += [(workspace_file.repository_name(url) or url, (url, None, None)) for url in add]
    root = folder.absolute()
    if root.exists() and not root.is_dir():
        raise AislandError(f"{root} is a file, not a folder.")
    own_root = locations.root_project(root) if locations.rooted(root) else None
    if own_root is not None:
        _root_repository(root, own_root.name, add=add, from_file=from_file, local=local, rewrite=rewrite)
        return
    existing = (root / ".git").exists()
    if existing and rewrite and (add or from_file is not None or local or untracked):
        raise AislandError("in an existing repository --rewrite writes its files and nothing else: run it on its own.")
    _refuse_a_bak_in_the_way(root, rewrite)
    if existing and rewrite:
        console.echo(f"==> Rewrote in {root}")
        for row in _write_starting_files(root, rewrite, only_rewrite=True):
            console.echo(row)
        return
    if existing and local:
        raise AislandError(f"{root} is already a git repository: --local makes a new one that only this machine has.")
    if existing and from_file is not None:
        raise AislandError(
            f"{root} is already a git repository, with a workspace.toml of its own: add projects with --add."
        )
    _say(f"==> {'Setting up' if existing else 'Creating'} workspace in {root}")
    if existing:
        _build(root, existing, plan, from_file, rewrite, local, untracked)
        return
    # A new workspace that fails half way (a project that cannot be cloned, an interrupt) leaves nothing it made, so
    # the same command runs again; a folder that held files before is never deleted.
    made_here = not root.exists() or not any(root.iterdir())
    try:
        _build(root, existing, plan, from_file, rewrite, local, untracked)
    except (click.ClickException, KeyboardInterrupt, OSError, subprocess.CalledProcessError) as exc:
        message = exc.message if isinstance(exc, click.ClickException) else f"init stopped: {exc or type(exc).__name__}"
        if made_here:
            shutil.rmtree(root, ignore_errors=True)
            raise AislandError(
                f"{message}\n{root} is removed again: this init made it. Run the same command once the cause is fixed."
            ) from exc
        raise AislandError(
            f"{message}\n{root} held files before this init, so it is left as it stopped: remove {root / '.git'} and "
            ".gitmodules, then run the same command again."
        ) from exc


#: The root repository's own ignore line beside a root project: every file, so it never records one.
RECORDS_NOTHING = "/*"


def _root_repository(
    root: Path,
    own_root: str,
    add: Sequence[str],
    from_file: Optional[Path],
    local: bool,
    rewrite: Sequence[StartingFile],
) -> None:
    """Make the folder holding the root project ``own_root`` a root repository that records no project (the module
    docstring), or keep the one there; refuse first what would add submodules or files beside the root project."""
    given = [
        option
        for option, value in (("--add", add), ("--from", from_file), ("--local", local), ("--rewrite", rewrite))
        if value
    ]
    if given:
        raise AislandError(
            f"{root} holds the workspace's root project, {own_root}: init makes the folder a root repository that "
            f"records no project, and {', '.join(given)} would add submodules or files beside it. A project joins the "
            f"workspace as a row of {own_root}/workspace.toml, which the next aisland setup clones."
        )
    if (root / ".git").exists():
        rows = [_row(".git/", "kept (an existing repository)")]
    else:
        gitcmd.git(root, "init", "-q", check=True)
        rows = [_row(".git/", "git init: a root repository that records no project")]
    exclude = Path(
        gitcmd.git(root, "rev-parse", "--path-format=absolute", "--git-path", "info/exclude", check=True).stdout.strip()
    )
    lines = exclude.read_text().splitlines() if exclude.is_file() else []
    if RECORDS_NOTHING not in lines:
        exclude.parent.mkdir(parents=True, exist_ok=True)
        atomic.write_text(exclude, "\n".join([*lines, RECORDS_NOTHING]) + "\n")
    rows.append(_row(".git/info/exclude", f"{RECORDS_NOTHING}: every file ignored, so nothing is ever staged"))
    staged = gitcmd.git(root, "ls-files").stdout.split()
    if staged:
        rows.append(_row("", f"{len(staged)} path(s) staged before: take them out with git rm -r --cached -- ."))
    ok = install_git_aliases(root, quiet=True)
    rows.append(
        _row("git aliases", "status-all, pull-all, … over every clone, the root project's included" if ok else "failed")
    )
    console.echo(f"==> Set up the root repository of workspace {get_workspace_name(root)} in {root}")
    for row in rows:
        console.echo(row)
    console.echo("Next:")
    console.echo(f"    cd {root}")
    console.echo(
        "    .venv/bin/aisland setup    # it also writes the hooks that give a session a worktree of the workspace"
    )


def _build(
    root: Path,
    existing: bool,
    plan: Sequence[Tuple[str, Optional[Tuple[str, Optional[str], Optional[str]]]]],
    from_file: Optional[Path],
    rewrite: Sequence[StartingFile],
    local: bool,
    untracked: bool,
) -> None:
    """Make or set up the workspace at ``root`` (:func:`init_workspace` checked every refusal first)."""
    if existing:
        rows = [_row(".git/", "kept (an existing repository)")]
    else:
        root.mkdir(parents=True, exist_ok=True)
        gitcmd.git(root, "init", "-q", check=True)
        rows = [_row(".git/", "git init (local: it tracks only the projects)" if local else "git init")]
    if local:
        local_workspace.mark(root)

    already = {path for path, _url, _branch in workspace_file.submodules(root)}
    _clone(root, plan)
    # A root init has just made holds no folder of clones of its own: a clone already here (one a --from project's
    # folder did not take) is a project, added as a submodule as it is.
    kept: List[str] = []
    if not existing:
        here = clones.found(root)
        if here:
            _say(f"{_INDENT}adding the clones already here as submodules …")
        rows += [_row("", line) for line in clones.add(root, here) if line.startswith("could not add")]
        kept = [clone.path for clone in here]
    rows += [
        _row(
            f"{path}/",
            f"submodule {url}"
            + (f" ({branch})" if branch else "")
            + (" — the clone already here, kept as it is" if path in kept else ""),
        )
        for path, url, branch in workspace_file.submodules(root)
        if path not in already
    ]

    _say(f"{_INDENT}writing the starting files, the git aliases and the agent rules …")
    rows += _write_starting_files(root, rewrite)

    if from_file is not None:
        atomic.write_text(root / workspace_file.FILE_NAME, from_file.read_text())
    workspace_file.refresh(root)
    if (root / workspace_file.FILE_NAME).is_file():
        rows.append(_row(workspace_file.FILE_NAME, "the projects, how to start another machine from them"))

    aliases = "pull-all, push-all, … in the local git config" if install_git_aliases(root, quiet=True) else "failed"
    rows.append(_row("git aliases", aliases))

    had_agents_md = (root / "AGENTS.md").exists()
    notes = install_harness(root)
    rows.append(
        _row(".agents/", f"harness: {harness_summary(harness_sets(root))} (`.claude/commands` links to its commands)")
    )
    if not had_agents_md:
        rows.append(_row("AGENTS.md", "written (imports the rules; CLAUDE.md and GEMINI.md link to it)"))
    rows += [_row("", note) for note in notes]

    if untracked:  # `[workspace] track = false`: the projects of today and those added later
        changes = tracking.set_committed(root, (), track=False)
        rows += [_row(change.project, "untracked: the root records none of its commits") for change in changes]
    settled = local_workspace.settle(root)
    if settled.committed:
        made = ", ".join(settled.committed) if settled.error is None else f"not made: {settled.error}"
        rows.append(_row("first commit", made))

    console.echo(f"==> {'Set up' if existing else 'Created'} workspace {get_workspace_name(root)} in {root}")
    for row in rows:
        console.echo(row)
    console.echo("Next:")
    console.echo(f"    cd {root}")
    if not runs_from_venv_of(root):
        console.echo("    uv venv --seed .venv && .venv/bin/pip install aisland")
    console.echo("    .venv/bin/aisland setup")
