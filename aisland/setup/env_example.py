"""The workspace's example environment: each project's two lists of variables, and the two files made of them.

A project lists, in ``<project>/env.complete``, every environment variable a person may set for it — one
commented-out ``# NAME=VALUE  description`` line each — and declares the names its code reads that nobody sets in
``.env`` (``# not for .env: NAME NAME — reason``). Its ``env.example``, in the same format, holds the few a person
normally sets. ``aisland workspace env-example`` concatenates each kind into the workspace's ``env.complete`` and
``env.example``: projects in dependency order, so a variable several projects read is listed once, under the project
that defines it (the first library reading it), the others named and any other wording of it kept. A new machine
copies ``env.example`` to ``.env``; ``--missing`` prints what an existing ``.env`` does not mention yet.
``aisland workspace env-test`` writes each project's ``tests/test_env_example.py`` from one template: it fails when
the project's code or shipped configs read a variable its ``env.complete`` does not list. A project never imports
aisland: the generated test stands alone.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Literal, Optional, Tuple, get_args

from aisland import console, locations
from aisland.errors import AislandError
from aisland.workspace.projects import dependency_order, discover_projects, get_project_metadata, workspace_folders

#: The two lists: every variable (``complete``), and the ones a person normally sets (``example``).
Kind = Literal["complete", "example"]
KINDS: Tuple[Kind, ...] = get_args(Kind)

#: A project's file of each kind, and the workspace's (generated, never committed: the starting ``.gitignore``
#: lists them).
FILE_NAMES: Dict[Kind, str] = {"complete": "env.complete", "example": "env.example"}
COMPLETE = FILE_NAMES["complete"]
EXAMPLE = FILE_NAMES["example"]

#: The template ``aisland workspace env-test`` writes into each project as ``tests/test_env_example.py``.
TEST_TEMPLATE = locations.PACKAGE_DIR / "templates" / "test_env_example.py.template"
TEST_PATH = Path("tests") / "test_env_example.py"

_ENTRY = re.compile(r"^#\s*([A-Z_][A-Z0-9_]*)=(\S*)(?:\s{2,}(\S.*))?$")
_ENTRY_START = re.compile(r"^#\s*([A-Z_][A-Z0-9_]*)=")
_SETS = re.compile(r"^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=")
_NOT_FOR_ENV = re.compile(r"^#\s*not for \.env:\s*(.+?)\s+(?:—|--|-)\s+(.+)$")
_HEADING = re.compile(r"^#\s*--\s+(.+)$")
#: A name ``.env`` mentions: set, exported or commented out.
_MENTIONED = re.compile(r"^\s*#?\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=", re.MULTILINE)

_PROVENANCE = """\
# =========================================================================
# AUTO-GENERATED FILE — DO NOT EDIT BY HAND
# Generated by: aisland workspace env-example
# Source: each project's {name} (aisland/setup/env_example.py)
# To regenerate: aisland workspace env-example
# =========================================================================
"""

_ABOUT: Dict[Kind, str] = {
    "complete": """\
# Every environment variable the workspace's projects read, each line commented out; the ones a person normally
# sets are in env.example. Copy a line you need into .env and uncomment it (project.bashrc exports .env).
# `aisland workspace env-example --missing` prints the variables a .env does not mention yet.
""",
    "example": """\
# The environment variables a person normally sets, each line commented out; env.complete lists every one. On a
# new machine:
#     cp env.example .env
# then uncomment and set the ones this machine needs (project.bashrc exports .env).
""",
}


@dataclass(frozen=True)
class Entry:
    """One variable of a project's file: ``# NAME=VALUE  description``."""

    name: str
    value: str
    description: str
    #: The ``# -- heading`` above it, if any.
    heading: Optional[str] = None

    @property
    def line(self) -> str:
        text = f"# {self.name}={self.value}"
        return f"{text}   {self.description}" if self.description else text


@dataclass
class ProjectEnv:
    """A project's file of one kind, read."""

    project: str
    path: Path
    #: Its first comment line, without the ``# ``.
    title: str = ""
    entries: List[Entry] = field(default_factory=list)
    #: The names its code reads that nobody sets in ``.env``, each with its reason.
    not_for_env: Dict[str, str] = field(default_factory=dict)


@dataclass
class Collected:
    """Every project's file of one kind, owners first, and the projects that have none."""

    kind: Kind
    projects: List[ProjectEnv]
    #: ``(project, why)``: ``no env.complete`` / ``no env.example``, or ``no checkout``.
    without: List[Tuple[str, str]]


@dataclass(frozen=True)
class Written:
    path: Path
    changed: bool
    variables: int
    projects: int
    without: List[Tuple[str, str]]


def read_project(path: Path, project: str) -> ProjectEnv:
    """Read ``path``; a line that would set a variable, or a malformed one, is refused naming its line."""
    env = ProjectEnv(project=project, path=path)
    heading: Optional[str] = None
    for number, raw in enumerate(path.read_text().splitlines(), start=1):
        line = raw.rstrip()
        where = f"{path}:{number}"
        if not line:
            continue
        if not line.startswith("#"):
            sets = _SETS.match(line)
            if sets:
                raise AislandError(
                    f"{where}: sets {sets.group(1)} outside a comment — every line of {path.name} is commented out"
                )
            raise AislandError(f"{where}: is not a comment — every line of {path.name} is a comment or blank")
        entry = _ENTRY.match(line)
        if entry:
            env.entries.append(Entry(entry.group(1), entry.group(2), entry.group(3) or "", heading))
            continue
        started = _ENTRY_START.match(line)
        if started:
            raise AislandError(f"{where}: two spaces part the value of {started.group(1)} from its description")
        plumbing = _NOT_FOR_ENV.match(line)
        if plumbing:
            for name in plumbing.group(1).replace(",", " ").split():
                env.not_for_env[name] = plumbing.group(2)
            continue
        titled = _HEADING.match(line)
        if titled:
            heading = titled.group(1)
            continue
        if not env.title:
            env.title = line.lstrip("#").strip()
    return env


def checked_out(folder: Path) -> bool:
    """A project folder holding files: its checkout, whatever git's ``active`` flag says (an optional project
    checked out by hand is read too)."""
    return folder.is_dir() and any(folder.iterdir())


def project_order(root: Path) -> List[Tuple[str, Path]]:
    """``(name, folder)`` of every checked-out project, each library before the projects that depend on it — the
    order of the editor's workspace file (``dependency_order`` over folder names) — so the first project
    reading a variable is the one that defines it."""
    checkouts = {(root / path).resolve(): name for name, path, _active in workspace_folders(root)}
    projects = sorted((get_project_metadata(p) for p in discover_projects(root)), key=lambda p: p["path"].name)
    ordered = [Path(p["path"]).resolve() for p in dependency_order(projects)]
    out = [(checkouts[folder], folder) for folder in ordered if folder in checkouts and checked_out(folder)]
    named = {name for name, _folder in out}
    out += [  # a checkout discovery does not know (no installable pyproject.toml): after the others, as listed
        (name, folder) for folder, name in checkouts.items() if name not in named and checked_out(folder)
    ]
    return out


def collect(root: Path, kind: Kind) -> Collected:
    """Every checked-out project's file of ``kind``, owners first (:func:`project_order`)."""
    projects: List[ProjectEnv] = []
    without: List[Tuple[str, str]] = []
    order = project_order(root)
    for name, folder in order:
        if (folder / FILE_NAMES[kind]).is_file():
            projects.append(read_project(folder / FILE_NAMES[kind], name))
        else:
            without.append((name, f"no {FILE_NAMES[kind]}"))
    present = {name for name, _folder in order}
    without += [(name, "no checkout") for name, _path, _active in workspace_folders(root) if name not in present]
    return Collected(kind, projects, without)


def render(collected: Collected) -> str:
    """The workspace's file of one kind: a section per project, a variable listed once, under its owner — the first
    project reading it — with the others named and each other wording of its description kept."""
    readers: Dict[str, List[Tuple[str, Entry]]] = {}
    for env in collected.projects:
        for entry in env.entries:
            readers.setdefault(entry.name, []).append((env.project, entry))
    name = FILE_NAMES[collected.kind]
    lines = [(_PROVENANCE.format(name=name) + _ABOUT[collected.kind]).rstrip("\n")]
    for env in collected.projects:
        lines += ["", f"# ===== {env.title or env.project}", ""]
        heading: Optional[str] = None
        for entry in env.entries:
            owner, first = readers[entry.name][0]
            if owner != env.project or first is not entry:
                continue
            if entry.heading and entry.heading != heading:
                if lines[-1] != "":
                    lines.append("")
                lines.append(f"# -- {entry.heading}")
                heading = entry.heading
            lines.append(entry.line)
            others = readers[entry.name][1:]
            if others:
                lines.append(f"#     also read by: {', '.join(project for project, _ in others)}")
            for project, other in others:
                if other.description and other.description != entry.description:
                    lines.append(f"#     {project}: {other.description}")
        if lines[-1] == "":
            lines[-1] = "# (every variable it reads is listed above)"
    if not collected.projects:
        lines += ["", f"# (no project has an {name} yet)"]
    names = [project for project, why in collected.without if why == f"no {name}"]
    if names:
        lines += ["", f"# ===== without an {name}: {', '.join(names)}"]
    return "\n".join(lines) + "\n"


def counts(written: Written) -> str:
    """``12 variables from 4 projects``, singular where it is one."""

    def many(n: int, word: str) -> str:
        return f"{n} {word}" + ("" if n == 1 else "s")

    return f"{many(written.variables, 'variable')} from {many(written.projects, 'project')}"


def write(root: Path) -> Dict[Kind, Written]:
    """Write the workspace's ``env.complete`` and ``env.example``; an unchanged one is left as it is. Every project
    file is read before either is written, so a malformed one leaves both as they were."""
    collected = {kind: collect(root, kind) for kind in KINDS}
    out: Dict[Kind, Written] = {}
    for kind in KINDS:
        text = render(collected[kind])
        target = root / FILE_NAMES[kind]
        changed = not target.is_file() or target.read_text() != text
        if changed:
            target.write_text(text)
        variables = len({e.name for env in collected[kind].projects for e in env.entries})
        out[kind] = Written(target, changed, variables, len(collected[kind].projects), collected[kind].without)
    return out


def write_for_setup(root: Path) -> None:
    """Setup's step: :func:`write`, each changed file said; a project's malformed file is said and setup goes on."""
    try:
        written = write(root)
    except AislandError as error:
        console.echo(f"==> {COMPLETE} and {EXAMPLE} not written: {error.message}")
        return
    for kind, result in written.items():
        if result.changed:
            console.echo(f"==> Wrote {FILE_NAMES[kind]} ({counts(result)})")


def missing(root: Path, env_file: Path) -> List[Tuple[str, Entry]]:
    """``(owner, entry)`` for each variable of the projects' ``env.complete`` ``env_file`` does not mention at all."""
    mentioned = set(_MENTIONED.findall(env_file.read_text()))
    seen = set()
    out: List[Tuple[str, Entry]] = []
    for env in collect(root, "complete").projects:
        for entry in env.entries:
            if entry.name not in mentioned and entry.name not in seen:
                out.append((env.project, entry))
            seen.add(entry.name)
    return out


def seed_text(root: Path) -> Optional[str]:
    """What a new ``.env`` starts as: the workspace's ``env.example`` when a project has one, else its
    ``env.complete`` when a project has that, else None."""
    for kind in ("example", "complete"):
        collected = collect(root, kind)
        if collected.projects:
            return render(collected)
    return None


def render_test(project: str) -> str:
    """A project's ``tests/test_env_example.py``, from the template."""
    return TEST_TEMPLATE.read_text().replace("__PROJECT__", project)


def write_test(root: Path, project: str, folder: str) -> Tuple[Path, bool]:
    """Write ``project``'s test into its ``folder``; an unchanged one is left. Its path (from ``root``), and whether
    it changed."""
    target = root / folder / TEST_PATH
    text = render_test(project)
    changed = not target.is_file() or target.read_text() != text
    if changed:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    return target.relative_to(root), changed
