"""``aisland workspace init <folder>``: make a folder a workspace aisland runs in.

A workspace, as aisland sees it, is a git repository whose projects are folders holding a ``pyproject.toml`` —
usually submodules. ``aisland setup`` then needs a ``.venv`` at the root and reads, when they exist, ``config.toml``
(sources, frameworks, trackers), ``.env`` (exported by ``project.bashrc``) and ``mypy.ini`` (its ``mypy_path`` kept
complete). This command writes those starting files, runs ``git init``, adds each ``--add`` repository as a
submodule and installs the workspace git aliases. It works the same whichever way aisland is installed; the
workspace it makes is one that aisland from a wheel works in (:mod:`aisland.locations`).

It never writes over a file that exists, and refuses a folder that already is a git repository: an existing
repository is set up with ``aisland setup``, not re-created.
"""

import subprocess
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import click

from aisland import locations
from aisland.manager import install_git_aliases

#: The terminal init the editor file's profile runs (`${workspaceFolder:<name>}/vscode-init-bash.sh`).
VSCODE_INIT_BASH = locations.PACKAGE_DIR / "templates" / "vscode-init-bash.sh"

_HEADER = """\
# =========================================================================
# Written by: aisland workspace init (aisland/aisland/workspace.py)
# A starting point that is yours to edit: init writes it once, into a new workspace, never over a file.
# =========================================================================
"""

#: What `aisland setup` and aisland's state write into the root, per machine — never committed.
_GITIGNORE = (
    _HEADER
    + """
# aisland's state when it runs from a wheel: services' data, vendored tools (aisland.locations).
.aisland/
# The workspace venv and this machine's environment (exported by project.bashrc).
.venv/
.env
# Generated by `aisland setup` / `aisland completion install`, per machine.
/project.bashrc
/pyrightconfig.json
/uv.toml
/.mcp.json
/.gemini/settings.json
/*.code-workspace
.project.bashrc.completion
user.bashrc
__pycache__/
"""
)

_ENV = (
    _HEADER
    + """
# This machine's environment, exported by `source project.bashrc`; never committed (.gitignore).
# Configs read these through `$VAR` substitution. Uncomment and set the ones this workspace uses:
# DATA_ROOT=/path/to/datasets
# MODEL_ROOT=/path/to/models
# RUN_DIR=/path/to/runs
"""
)

_CONFIG = (
    _HEADER
    + """
# The workspace's one committed configuration. Empty: every project is installed from its checkout, and
# `aisland setup` asks once which frameworks and trackers to install. Written by
# `aisland source set`, `aisland framework set` and `aisland tracker set`.
"""
)


def _mypy_ini(folders: Sequence[str]) -> str:
    return (
        (
            _HEADER
            + """
[mypy]
# The folders mypy searches for the workspace's packages; `aisland setup` adds each project it finds.
# Run mypy from the workspace root against a project folder: mypy <project>/
mypy_path = """
            + ":".join(folders)
        ).rstrip()
        + "\n"
    )


def _row(name: str, what: str) -> str:
    return f"    {name.ljust(26)}{what}"


def _submodule_paths(root: Path) -> List[Tuple[str, str]]:
    """``(path, url)`` of every submodule ``.gitmodules`` declares, in its order."""
    if not (root / ".gitmodules").is_file():
        return []
    listing = subprocess.run(
        ["git", "config", "-f", ".gitmodules", "--get-regexp", r"^submodule\..*\.(path|url)$"],
        cwd=root,
        capture_output=True,
        text=True,
    ).stdout
    paths: Dict[str, str] = {}
    urls: Dict[str, str] = {}
    for line in listing.splitlines():
        key, _, value = line.partition(" ")
        name, field = key[len("submodule.") :].rsplit(".", 1)
        (paths if field == "path" else urls)[name] = value
    return [(paths[name], urls.get(name, "")) for name in paths]


def init_workspace(folder: Path, add: Sequence[str] = ()) -> None:
    """Make ``folder`` a new workspace (see the module docstring). Raises :class:`click.ClickException` on refusal."""
    root = folder.absolute()
    if root.exists() and not root.is_dir():
        raise click.ClickException(f"{root} is a file, not a folder.")
    if (root / ".git").exists():
        raise click.ClickException(
            f"{root} is already a git repository. `aisland workspace init` starts a new one; "
            "in an existing repository run `aisland setup`."
        )
    root.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    rows = [_row(".git/", "git init")]

    for url in add:
        result = subprocess.run(["git", "submodule", "add", "-q", url], cwd=root, capture_output=True, text=True)
        if result.returncode != 0:
            raise click.ClickException(f"could not add {url} as a submodule: {result.stderr.strip()}")
    submodules = _submodule_paths(root)
    rows += [_row(f"{path}/", f"submodule {url}") for path, url in submodules]

    files = {
        ".gitignore": _GITIGNORE,
        ".env": _ENV,
        "config.toml": _CONFIG,
        "mypy.ini": _mypy_ini([path for path, _url in submodules if (root / path / "pyproject.toml").is_file()]),
        "vscode-init-bash.sh": VSCODE_INIT_BASH.read_text(),
    }
    for name, text in files.items():
        target = root / name
        if target.exists():
            rows.append(_row(name, "kept (it exists)"))
            continue
        target.write_text(text)
        rows.append(_row(name, "written"))

    aliases = "pull-all, push-all, … in the local git config" if install_git_aliases(root, quiet=True) else "failed"
    rows.append(_row("git aliases", aliases))

    click.echo(f"==> Created workspace {root.name} in {root}")
    for row in rows:
        click.echo(row)
    click.echo("Next:")
    click.echo(f"    cd {root}")
    click.echo("    uv venv --seed .venv && .venv/bin/pip install <the aisland wheel>")
    click.echo("    .venv/bin/aisland setup")
