"""The root ``uv.toml``: aisland's base overrides plus each activated project's own ``uv.toml``, and each
project's ``wheels/`` folder as a ``find-links`` path."""

import os
import re
import tomllib
from pathlib import Path
from typing import Any, Dict, List

import click
from packaging.requirements import InvalidRequirement, Requirement

# Workspace-wide uv settings that are no single project's concern. Merged into the generated
# root uv.toml beneath every activated project's own uv.toml. The never-true marker
# (`sys_platform == 'never'`) is uv's idiom for "drop this requirement everywhere".
#
# * ``lightning`` — the unified package conflicts with ``pytorch-lightning``, so it is dropped
#   in a workspace where something asks for ``pytorch-lightning``. It is NOT dropped elsewhere:
#   see ``_CONDITIONAL_OVERRIDES``.
# * ``opencv-python`` — it and ``opencv-python-headless`` install the SAME files (both RECORDs
#   claim ``cv2/cv2.abi3.so`` and ``cv2/.dylibs/*``) with DIFFERENT bundled native libraries, so
#   having both installed lets any install that moves one variant leave ``cv2/.dylibs/`` mixed
#   between two bundles — a dlopen failure at ``import cv2`` (seen: a leftover ffmpeg-6
#   ``libavformat.60`` beside the other wheel's ``libsrt.1.5.4``). The workspace keeps HEADLESS
#   only: nothing here needs the GUI build (ultralytics' cv2.imshow paths are all gated behind
#   ``check_imshow``, which try/excepts; first-party code uses cv2.resize and friends).
# * ``opencv-python-headless`` — pinned to the label-studio-sdk-compatible range because
#   ``roboflow`` pins ``==4.10.0.84`` while ``label-studio-sdk`` needs ``>=4.12,<5``: the two are
#   mutually unsatisfiable, so the choice is made explicitly here rather than left to install
#   order (verified: roboflow + rfdetr import fine on 4.13).
_ROOT_UV_BASE: Dict[str, Any] = {
    "override-dependencies": [
        "opencv-python ; sys_platform == 'never'",
        "opencv-python-headless>=4.12,<5",
    ],
}


#: Overrides that apply only where the conflict they exist for is actually possible, keyed by the
#: distribution whose presence makes it so. Dropping a requirement no project in this workspace
#: conflicts with is not conservative, it is silent breakage: another workspace (2026-10-20) has
#: no `pytorch-lightning` anywhere and two projects requiring `lightning` outright, so the blanket
#: override stripped a hard dependency and importing one of those projects failed on a venv that had
#: just reported a successful install. The workspace aisland is developed in, where this override was written, keeps
#: it unchanged — `pytorch-lightning` is declared by matrainer, deltaid and distilaide.
#:
#: The trigger is a mention ANYWHERE in a project's pyproject (base dependencies or any extra),
#: not just the selected extras: an override that appeared and vanished as extras were selected
#: would resolve differently run to run, which is worse than either answer on its own.
_CONDITIONAL_OVERRIDES: Dict[str, List[str]] = {
    "pytorch-lightning": ["lightning ; sys_platform == 'never'"],
}


def _mentions_distribution(pyproject_path: Path, distribution: str) -> bool:
    """True when ``distribution`` is required by a pyproject, in its dependencies or ANY extra."""
    try:
        data = tomllib.loads(pyproject_path.read_text())
    except (OSError, tomllib.TOMLDecodeError):
        return False
    project = data.get("project", {})
    requirements = list(project.get("dependencies", []) or [])
    for extra in (project.get("optional-dependencies", {}) or {}).values():
        requirements += list(extra or [])
    wanted = re.sub(r"[-_.]+", "-", distribution).lower()
    for raw in requirements:
        try:
            if re.sub(r"[-_.]+", "-", Requirement(str(raw)).name).lower() == wanted:
                return True
        except InvalidRequirement:
            continue
    return False


def _merge_uv(into: Dict[str, Any], other: Dict[str, Any]) -> None:
    """Merge ``other`` uv-config into ``into``: list values are unioned (dedup, order-preserving);
    scalars are last-wins."""
    for key, value in other.items():
        if isinstance(value, list):
            base = into.get(key)
            base_list = list(base) if isinstance(base, list) else []
            into[key] = base_list + [v for v in value if v not in base_list]
        else:
            into[key] = value


def _emit_uv_toml(data: Dict[str, Any]) -> str:
    """Hand-emit the flat key set uv.toml uses (string scalars + string/scalar lists + bools).

    No `tomli-w` dependency for the realistic case; an unsupported (table/array-of-table) key is
    skipped with a warning rather than mis-serialized — add `tomli-w` if a project ever needs one.
    """
    header = (
        "# =========================================================================\n"
        "# AUTO-GENERATED by `aisland setup` (uv_config.write_root_uv_toml) — DO NOT EDIT.\n"
        "# Merged from the workspace base + each ACTIVATED project's uv.toml and wheels/ folder\n"
        "# (find-links). Regenerate\n"
        "# with `aisland setup`. Gitignored: a private index is present only when its\n"
        "# project is activated, so a machine that skips it never contacts that index.\n"
        "# =========================================================================\n\n"
    )
    lines: List[str] = []
    for key, value in data.items():
        if isinstance(value, bool):
            lines.append(f"{key} = {'true' if value else 'false'}")
        elif isinstance(value, (int, float)):
            lines.append(f"{key} = {value}")
        elif isinstance(value, str):
            lines.append(f'{key} = "{value}"')
        elif isinstance(value, list):
            lines.append(f"{key} = [")
            for item in value:
                lines.append(f'    "{item}",')
            lines.append("]")
        else:
            click.echo(f"  - Warning: skipping uv.toml key {key!r} (unsupported type {type(value).__name__})")
    return header + "\n".join(lines) + "\n"


def write_root_uv_toml(workspace_root: Path, activated: List[dict]) -> None:
    """Generate ``<workspace>/uv.toml`` = workspace base merged with each activated project's uv.toml.

    Gitignored + regenerated on every setup (like ``pyrightconfig.json`` / ``.gemini/settings.json``)
    so a private index (a company's artifact repository) is present ONLY when that project
    is activated — never committed, so a machine that doesn't activate it never stalls on the index.
    """
    merged: Dict[str, Any] = {k: (list(v) if isinstance(v, list) else v) for k, v in _ROOT_UV_BASE.items()}
    # Conditional overrides: added only where some activated project actually names the
    # conflicting distribution (see _CONDITIONAL_OVERRIDES for why a blanket one is unsafe).
    for distribution, overrides in _CONDITIONAL_OVERRIDES.items():
        if any(_mentions_distribution(Path(p["path"]) / "pyproject.toml", distribution) for p in activated):
            merged.setdefault("override-dependencies", [])
            merged["override-dependencies"] = overrides + [
                o for o in merged["override-dependencies"] if o not in overrides
            ]
    n_merged = 0
    for project in activated:
        uv_file = Path(project["path"]) / "uv.toml"
        if not uv_file.exists():
            continue
        try:
            with open(uv_file, "rb") as f:
                _merge_uv(merged, tomllib.load(f))
            n_merged += 1
        except (OSError, tomllib.TOMLDecodeError) as e:
            click.echo(f"  - Warning: failed to read {uv_file}: {e}")
    # Each activated project's `aisland wheels` folder (its `wheels.yaml` marks it) is a find-links path, written
    # relative to this file, which uv resolves against the file's own folder from anywhere below it: the wheels of
    # what PyPI lacks reach every install run in the workspace, setup's included. uv prefers a find-links wheel over
    # the index's of the same version (pip does not); a project checked out here still installs from its checkout.
    folders = [
        os.path.relpath(Path(p["path"]) / "wheels", workspace_root)
        for p in activated
        if (Path(p["path"]) / "wheels" / "wheels.yaml").is_file()
    ]
    if folders:
        _merge_uv(merged, {"find-links": folders})
    out = workspace_root / "uv.toml"
    out.write_text(_emit_uv_toml(merged))
    extra = len(merged.get("extra-index-url", []) or [])
    wheels = f"; {len(folders)} wheels folder(s)" if folders else ""
    click.echo(f"==> Wrote {out} (base + {n_merged} project uv.toml; {extra} extra index URL(s){wheels})")
