"""The extra ``aisland wheels build <project> --extra NAME`` writes into the project's ``pyproject.toml``.

``uv pip install -e ./<project>[NAME]`` then installs the project editable together with every wheel of its
``wheels/`` folder, in one command and with no script: the extra names each built wheel's distribution, and a
``[tool.uv.sources]`` entry per distribution, conditional on the extra, sends uv to the wheel's file. Without the
extra no source applies, so an install without it — the workspace's editable checkouts — is unchanged. A wheel
rebuilt under the same version is a different file to uv, which installs it again; ``install.py --reinstall`` is
not needed. pip reads no ``[tool.uv.sources]``: the extra is for uv.

The two pieces are written between marker lines, the extra at the end of ``[project.optional-dependencies]`` and
the sources at the end of ``[tool.uv.sources]`` (each table appended when the file has none), and a rerun replaces
what is between the markers and nothing else. Everything is checked before any wheel is built
(:func:`check_extra`): the project must list the extra in ``[tool.aisland] manual-extras`` — ``aisland setup``
would otherwise install it, and the wheels would replace the workspace's checkouts — and no key outside the
markers may hold the extra or one of the sources.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import AbstractSet, List, Optional, Sequence, Set, Tuple

from aisland import pyproject as pyproject_toml
from aisland.errors import AislandError

#: The first and last line of each generated piece.
BEGIN = "# >>> generated by aisland wheels build"
END = "# <<< generated by aisland wheels build"

_OPTIONAL = "project.optional-dependencies"
_SOURCES = "tool.uv.sources"

#: A normalized extra name (PEP 685): what pip and uv compare extras by.
_EXTRA_NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
_HEADER = re.compile(r"^\[\s*([^\[\]]+?)\s*\]\s*(#.*)?$")


@dataclass(frozen=True)
class ExtraWheel:
    """One wheel the extra installs: its distribution's name and its file in ``wheels/``."""

    distribution: str
    wheel: str


def _where(path: Path, line: int) -> str:
    return f"{path}:{line}"


def _headers(lines: Sequence[str]) -> List[Tuple[int, str]]:
    """``(index, table)`` of each ``[table]`` header line, ``[[array]]`` headers included as their name."""
    found = []
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("[["):
            found.append((index, stripped.strip("[] ")))
            continue
        match = _HEADER.match(stripped)
        if match:
            found.append((index, match.group(1).replace('"', "").replace(" ", "")))
    return found


def _blocks(path: Path, lines: Sequence[str]) -> List[Tuple[int, int]]:
    """``(begin, end)`` index of each generated piece; an unclosed or nested marker is refused at its line."""
    blocks: List[Tuple[int, int]] = []
    begin: Optional[int] = None
    for index, line in enumerate(lines):
        if line.startswith(BEGIN):
            if begin is not None:
                raise AislandError(
                    f"{_where(path, index + 1)}: a generated block starts inside the one opened at line {begin + 1}"
                )
            begin = index
        elif line.startswith(END):
            if begin is None:
                raise AislandError(f"{_where(path, index + 1)}: a generated block ends that never started")
            blocks.append((begin, index))
            begin = None
    if begin is not None:
        raise AislandError(f"{_where(path, begin + 1)}: a generated block is never closed ({END!r})")
    return blocks


def _inside(path: Path, lines: Sequence[str]) -> Set[int]:
    return {index for begin, end in _blocks(path, lines) for index in range(begin, end + 1)}


def _without_blocks(path: Path, lines: Sequence[str]) -> List[str]:
    inside = _inside(path, lines)
    return [line for index, line in enumerate(lines) if index not in inside]


def _key_line(lines: Sequence[str], table: str, key: str, skip: AbstractSet[int] = frozenset()) -> int:
    """The 1-based line of ``key`` in ``table``, the rows in ``skip`` passed over (the table's header when the key
    is not found, else 1)."""
    headers = _headers(lines)
    for position, (index, name) in enumerate(headers):
        if name != table:
            continue
        stop = headers[position + 1][0] if position + 1 < len(headers) else len(lines)
        for row in range(index + 1, stop):
            if row not in skip and re.match(rf'^\s*"?{re.escape(key)}"?\s*=', lines[row]):
                return row + 1
        return index + 1
    return 1


def _table(data: pyproject_toml.Table, dotted: str) -> pyproject_toml.Table:
    node: object = data
    for part in dotted.split("."):
        node = node.get(part, {}) if isinstance(node, dict) else {}
    return node if isinstance(node, dict) else {}


#: The first line of a generated extra block names its extra: what a later build without ``--extra`` keeps current.
_REMEMBERED = re.compile(rf"^{re.escape(BEGIN)}: the `([^`]+)` extra")


def remembered_extra(pyproject: Path) -> Optional[Tuple[str, int]]:
    """The extra a generated block in ``pyproject`` writes, and its 1-based line; ``None`` when it has none."""
    for index, line in enumerate(pyproject.read_text(encoding="utf-8").splitlines()):
        match = _REMEMBERED.match(line)
        if match:
            return match.group(1), index + 1
    return None


def check_extra(pyproject: Path, extra: str, distributions: Sequence[str]) -> None:
    """Refuse ``--extra`` before anything is built: a name that is no normalized extra name, a project that does not
    list it in ``[tool.aisland] manual-extras``, or a key outside the generated blocks that already holds the extra
    or a source of one of ``distributions``. Each refusal names the file and the line."""
    if not _EXTRA_NAME.match(extra):
        raise AislandError(
            f"--extra {extra!r} is no extra name: lowercase letters and digits joined by '-' (as {extra.lower()!r})"
        )
    text = pyproject.read_text(encoding="utf-8")
    lines = text.splitlines()
    inside = _inside(pyproject, lines)
    rest = [line for index, line in enumerate(lines) if index not in inside]
    data = pyproject_toml.parse("\n".join(rest) + "\n", pyproject)
    manual = _table(data, "tool.aisland").get("manual-extras", [])
    if extra not in manual:
        line = _key_line(lines, "tool.aisland", "manual-extras")
        raise AislandError(
            f"{_where(pyproject, line)}: --extra {extra} needs {extra!r} in [tool.aisland] manual-extras — "
            f"`aisland setup` would otherwise install it, and its wheels would replace the workspace's checkouts"
        )
    if extra in _table(data, _OPTIONAL):
        line = _key_line(lines, _OPTIONAL, extra, inside)
        raise AislandError(
            f"{_where(pyproject, line)}: the extra {extra!r} is written by hand; --extra writes it — remove it"
        )
    taken = sorted(set(_table(data, _SOURCES)) & set(distributions))
    if taken:
        raise AislandError(
            f"{_where(pyproject, _key_line(lines, _SOURCES, taken[0], inside))}: [tool.uv.sources] already has "
            f"{', '.join(taken)}; --extra {extra} writes a source for each wheel — remove "
            f"{'it' if len(taken) == 1 else 'them'}"
        )


def _string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _key(name: str) -> str:
    """A TOML key: bare when TOML allows it (``lib-b``), quoted otherwise (a name with a dot)."""
    return name if re.match(r"^[A-Za-z0-9_-]+$", name) else _string(name)


def render_blocks(extra: str, wheels: Sequence[ExtraWheel], command: str) -> Tuple[List[str], List[str]]:
    """The extra's lines and the sources' lines, each between the marker lines, under the provenance header."""
    header = [
        f"#     Generated by: {command}",
        "#     Source: aisland/aisland/wheels/extra.py (render_blocks)",
        f"#     To regenerate: {command}",
    ]
    names = sorted(wheels, key=lambda w: w.distribution)
    extra_lines = [
        f"{BEGIN}: the `{extra}` extra — `uv pip install -e .[{extra}]` installs every wheel in wheels/",
        *header,
        f"{extra} = [" + ("" if names else "]"),
    ]
    if names:
        extra_lines += [f"    {_string(w.distribution)}," for w in names] + ["]"]
    extra_lines.append(END)
    source_lines = [f"{BEGIN}: each wheel of the `{extra}` extra, from its file in wheels/", *header]
    source_lines += [
        f"{_key(w.distribution)} = [{{ path = {_string('wheels/' + w.wheel)}, extra = {_string(extra)} }}]"
        for w in names
    ]
    source_lines.append(END)
    return extra_lines, source_lines


def _insert(lines: List[str], table: str, block: List[str]) -> List[str]:
    """``block`` at the end of ``table`` — after its last line that is neither blank nor a comment, so a comment
    above the next table stays with it — or the table appended to the file when it has none."""
    headers = _headers(lines)
    for position, (index, name) in enumerate(headers):
        if name != table:
            continue
        stop = headers[position + 1][0] if position + 1 < len(headers) else len(lines)
        last = index
        for row in range(index + 1, stop):
            stripped = lines[row].strip()
            if stripped and not stripped.startswith("#"):
                last = row
        return lines[: last + 1] + block + lines[last + 1 :]
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    return lines + ["", f"[{table}]", *block]


def write_extra(pyproject: Path, extra: str, wheels: Sequence[ExtraWheel], command: str) -> bool:
    """Write the extra and its sources into ``pyproject`` (see the module docstring); ``True`` when the file
    changed. The result is parsed before it is written, and must hold exactly what was generated."""
    text = pyproject.read_text(encoding="utf-8")
    lines = _without_blocks(pyproject, text.splitlines())
    extra_block, source_block = render_blocks(extra, wheels, command)
    lines = _insert(lines, _OPTIONAL, extra_block)
    lines = _insert(lines, _SOURCES, source_block)
    new = "\n".join(lines) + "\n"
    data = pyproject_toml.parse(new, pyproject)  # check_extra parsed the rest: the generated blocks read back
    expected = sorted(w.distribution for w in wheels)
    if _table(data, _OPTIONAL).get(extra) != expected:  # pragma: no cover - the rendering above guarantees it
        raise AislandError(f"{pyproject}: the written extra {extra!r} does not read back as generated")
    if new == text:
        return False
    pyproject.write_text(new, encoding="utf-8")
    return True
