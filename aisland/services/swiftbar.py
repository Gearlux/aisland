"""SwiftBar, the macOS menu-bar app: aisland's menus of each project's Jenkins jobs and GitHub Actions runs."""

import os
import platform
import shlex
import subprocess
import time
from pathlib import Path
from typing import Any, List, Optional, Sequence, Tuple, Union
from urllib.parse import quote

import click

from aisland import console, failures, gitcmd, locations, paths, probe
from aisland.services.base import BaseService, ServiceState, service_state, styled_state
from aisland.services.jenkins import JenkinsService
from aisland.setup import provision
from aisland.workspace.github import github_repository
from aisland.workspace.model import Workspace
from aisland.workspace.projects import dependency_order, get_workspace_root

#: The bodies of the menu scripts ``aisland swiftbar init`` writes, each ``<[ name ]>`` filled in by :func:`_render_script`.
TEMPLATES_DIR = locations.PACKAGE_DIR / "templates" / "swiftbar"
#: How long a call to macOS about SwiftBar (`defaults`, `open`, `pkill`) may take; each answers in well under a second.
SWIFTBAR_SECONDS = 30


def _render_script(template: str, **values: Union[str, Sequence[str]]) -> str:
    """The menu script made from ``template`` (a file of :data:`TEMPLATES_DIR`): the shebang and the provenance header,
    then the template with each ``<[ key ]>`` replaced by ``values[key]`` as bash words — a string one word, a list one
    word per item, each quoted (``shlex.quote``), so a folder or job name holding a space, a quote or a ``$`` stays
    that name and never runs as code."""
    body = (TEMPLATES_DIR / template).read_text()
    for key, value in values.items():
        words = [value] if isinstance(value, str) else list(value)
        body = body.replace(f"<[ {key} ]>", " ".join(shlex.quote(word) for word in words))
    rule = "# " + "=" * 73
    header = [
        "#!/bin/bash",
        rule,
        "# AUTO-GENERATED FILE — DO NOT EDIT BY HAND",
        "# Generated by: aisland swiftbar init",
        f"# Source template: aisland/templates/swiftbar/{template}",
        "# To regenerate:  aisland swiftbar init",
        rule,
    ]
    return "\n".join(header) + "\n" + body


def swiftbar_installed() -> bool:
    """Whether the SwiftBar app is in this machine's or this user's Applications folder (where Homebrew's cask puts it)."""
    return any((folder / "SwiftBar.app").exists() for folder in (Path("/Applications"), Path.home() / "Applications"))


class SwiftBarService(BaseService):
    """SwiftBar Plugin Management Service."""

    def __init__(self) -> None:
        super().__init__("swiftbar")
        self.plugins_dir = self.service_data_dir / "plugins"  # made when the first script is written

    @staticmethod
    def _require_macos() -> bool:
        """True on macOS; otherwise report and skip.

        SwiftBar is a macOS-only menu bar app and every action here shells out
        to macOS-only tools (``open``, ``defaults``, ``pkill``). Note that
        ``os.name`` is NOT a valid guard — Linux is also ``"posix"``.
        """
        if platform.system() != "Darwin":
            console.echo("SwiftBar is only supported on macOS — skipping.")
            return False
        return True

    def _get_github_repo(self, path: Path) -> Optional[str]:
        """``owner/name`` of the GitHub repository ``path``'s origin names; None for no repository or another host."""
        if not (path / ".git").exists():  # a submodule's .git is a file, the root's a folder
            return None
        repository = github_repository(gitcmd.remote_url(path) or "")
        return f"{repository.owner}/{repository.name}" if repository else None

    def _dependency_ordered_projects(self, workspace_root: Path) -> List[Path]:
        """Project folders, dependencies before their dependents and otherwise by name, so the order is the same
        on every machine. The workspace root itself is excluded (it has no ``pyproject.toml``); callers add it."""
        projects = sorted(Workspace(workspace_root).metadata, key=lambda p: p["name"])
        return [p["path"] for p in dependency_order([p for p in projects if p["name"]])]

    def init_scripts(self) -> None:
        """Scan workspace and generate SwiftBar scripts for Jenkins and GitHub."""
        if not self._require_macos():
            return
        console.echo(f"Initializing SwiftBar scripts in {self.plugins_dir}...")
        jenkins_projects, github_repos = self._monitored(get_workspace_root())
        console.echo(f"  - Monitored Jenkins jobs: {', '.join(jenkins_projects)}")
        console.echo(f"  - Monitored GitHub repos: {', '.join(github_repos)}")
        self._generate_jenkins_script(jenkins_projects)
        self._generate_github_script(github_repos)
        console.echo("SwiftBar scripts initialized.")
        if console.confirm(f"Do you want to point SwiftBar directly to {self.plugins_dir}?"):
            self._use_plugins_dir()
        else:
            console.echo(f"\nPlease manually point SwiftBar to: {self.plugins_dir}")

    def _monitored(self, workspace_root: Path) -> Tuple[List[str], List[str]]:
        """The Jenkins jobs and the GitHub repositories the menu watches: each project's, dependencies before
        dependents, then the workspace root's (no project, but it has jobs and a remote too)."""
        jobs_dir = paths.data_dir() / "jenkins" / "jobs"
        jenkins_projects: List[str] = []
        github_repos: List[str] = []
        for folder in [*self._dependency_ordered_projects(workspace_root), workspace_root]:
            jenkins_projects += [job for job in (folder.name, f"{folder.name}.local") if (jobs_dir / job).exists()]
            repository = self._get_github_repo(folder)
            if repository:
                github_repos.append(repository)
        return jenkins_projects, github_repos

    def _use_plugins_dir(self) -> None:
        """Point SwiftBar at the plugins folder, hide the workspace's agent files from its menu and start it again."""
        defaults = ["defaults", "write", "com.ameba.SwiftBar"]
        try:
            self.stop()  # SwiftBar writes its settings cleanly only when it is not running
            for key in ("PluginDirectory", "PluginsDirectory"):
                subprocess.run([*defaults, key, str(self.plugins_dir)], check=True, timeout=SWIFTBAR_SECONDS)
            subprocess.run([*defaults, "MakePluginExecutable", "-bool", "YES"], check=True, timeout=SWIFTBAR_SECONDS)
            subprocess.run(
                [*defaults, "DisabledPlugins", "-array", "CLAUDE.md", "AGENTS.md", "GEMINI.md"],
                check=True,
                timeout=SWIFTBAR_SECONDS,
            )
            console.echo(f"  - SwiftBar configured to use: {self.plugins_dir}")
            # The URL scheme as well, so a running app makes its bookmark of the folder.
            subprocess.run(
                ["open", "-g", f"swiftbar://changePluginsDirectory?path={quote(str(self.plugins_dir))}"],
                check=False,
                timeout=SWIFTBAR_SECONDS,
            )
            self.launch()
        except (OSError, subprocess.SubprocessError) as e:
            failures.report(f"  - Error: failed to configure SwiftBar: {e}")

    def launch(self) -> None:
        """Start the SwiftBar application — installed first, once the user agrees, when it is missing."""
        if not self._require_macos():
            return
        if not swiftbar_installed():
            provision.ask_to_install("swiftbar")

        console.echo("Starting SwiftBar...")
        try:
            subprocess.run(["open", "-a", "SwiftBar"], check=True, timeout=SWIFTBAR_SECONDS)
            console.echo("  - SwiftBar launched.")
        except subprocess.SubprocessError as e:
            failures.report(f"  - Error launching SwiftBar: {e}")

    def stop(self) -> None:
        """Stop the SwiftBar application."""
        if not self._require_macos():
            return

        console.echo("Stopping SwiftBar...")
        try:
            # -x: the process named SwiftBar, never one whose name merely contains it.
            subprocess.run(["pkill", "-x", "SwiftBar"], check=False, timeout=SWIFTBAR_SECONDS)
            console.echo("  - SwiftBar stopped.")
        except (OSError, subprocess.TimeoutExpired) as e:
            failures.report(f"  - Error stopping SwiftBar: {e}")

    def restart(self, **kwargs: Any) -> None:  # Any: launch's options, each typed there
        """Restart SwiftBar."""
        if not self._require_macos():
            return
        self.stop()
        time.sleep(1)
        self.launch()

    def remove(self) -> None:
        """Clear SwiftBar configuration if it points to this workspace."""
        if not self._require_macos():
            return
        keys = ["PluginDirectory", "PluginsDirectory"]
        for key in keys:
            try:
                current = subprocess.check_output(
                    ["defaults", "read", "com.ameba.SwiftBar", key], text=True, timeout=SWIFTBAR_SECONDS
                ).strip()
                if current == str(self.plugins_dir):
                    console.echo(f"Clearing SwiftBar {key} setting (was {self.plugins_dir})...")
                    self.stop()
                    subprocess.run(
                        ["defaults", "delete", "com.ameba.SwiftBar", key], check=True, timeout=SWIFTBAR_SECONDS
                    )
                    console.echo(f"  - SwiftBar {key} configuration cleared.")
            except subprocess.CalledProcessError:
                # Key might not exist or app not installed
                pass
            except (OSError, subprocess.TimeoutExpired) as e:
                failures.report(f"  - Error clearing SwiftBar {key} configuration: {e}")

    def wipes(self) -> str:
        return "no data: SwiftBar stops showing this workspace's menus"

    def reset(self) -> None:
        """Alias for remove() to maintain consistency with other services."""
        self.remove()

    def state(self) -> ServiceState:
        """Whether the SwiftBar app runs (``pgrep -x``: the process named SwiftBar, as :meth:`stop` reads it);
        ``not supported`` off macOS."""
        if platform.system() != "Darwin":
            return service_state(self.name, "not supported")
        return service_state(self.name, "running" if probe.succeeds(["pgrep", "-x", "SwiftBar"]) else "stopped")

    def status(self) -> None:
        """Display SwiftBar status."""
        state = self.state()["state"]
        words = "Not supported (macOS only)" if state == "not supported" else None
        console.echo(f"  Swiftbar        : {styled_state(state, words)}")

    def info(self) -> None:
        """Show detailed SwiftBar configuration."""
        console.echo(click.style("Swiftbar:", bold=True))
        if platform.system() != "Darwin":
            console.echo(f"  Status        : {click.style('Not supported (macOS only)', fg='yellow')}")
            return
        if probe.succeeds(["pgrep", "-x", "SwiftBar"]):
            console.echo(f"  Status        : {click.style('Running', fg='green')}")
        else:
            console.echo(f"  Status        : {click.style('Stopped', fg='red')}")
        console.echo(f"  Plugins dir   : {self.plugins_dir}")
        if self.plugins_dir.exists():
            scripts = sorted(p.name for p in self.plugins_dir.iterdir() if p.is_file())
            if scripts:
                console.echo(f"  Plugin scripts: {', '.join(scripts)}")
            else:
                console.echo("  Plugin scripts: (none — run `aisland swiftbar init`)")
        console.echo(f"  App support   : {Path.home() / 'Library' / 'Application Support' / 'SwiftBar'}")

    def _generate_jenkins_script(self, projects: List[str]) -> None:
        """Generate the Jenkins status script."""
        script_path = self.plugins_dir / "jenkins_status.5m.sh"

        # Resolve JENKINS_HOME relative to aisland data
        # aisland/aisland/services/swiftbar.py -> aisland/data/jenkins
        jenkins_home = paths.data_dir() / "jenkins"

        # Check for read access
        if not os.access(jenkins_home, os.R_OK):
            console.echo(
                click.style(
                    f"  [WARNING] No read access to Jenkins home: {jenkins_home}",
                    fg="yellow",
                )
            )
            console.echo("            The SwiftBar script might not display project status correctly.")
            console.echo("            Please check your terminal's permissions for the 'aisland' data directory.")

        content = _render_script(
            "jenkins_status.sh",
            jenkins_home=str(jenkins_home),
            projects=projects,
            # The menu links the Jenkins running now, on the port it runs on (else its default).
            jenkins_url=JenkinsService().url(),
        )
        self.plugins_dir.mkdir(parents=True, exist_ok=True)
        script_path.write_text(content)
        script_path.chmod(0o755)
        console.echo(f"  - Generated {script_path.name}")

    def _generate_github_script(self, github_repos: List[str]) -> None:
        """Generate the GitHub status script."""
        script_path = self.plugins_dir / "gh_status.10m.sh"

        content = _render_script("gh_status.sh", repos="\n".join(github_repos))
        self.plugins_dir.mkdir(parents=True, exist_ok=True)
        script_path.write_text(content)
        script_path.chmod(0o755)
        console.echo(f"  - Generated {script_path.name}")
