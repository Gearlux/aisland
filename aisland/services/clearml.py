"""ClearML server — upstream's docker-compose stack, redirected into the workspace.

ClearML's server is seven containers (apiserver, webserver, fileserver, elasticsearch,
mongo, redis, agent-services), and upstream publishes the compose file that wires them.
This service does NOT reimplement that topology: it fetches upstream's file at a PINNED
release tag, verifies it against a pinned SHA-256 (the same rule
``manager.USERSPACE_TOOLS`` follows for downloaded binaries), and layers a small generated
override on top.

**The override exists for one reason.** Upstream hardcodes ``/opt/clearml/...`` as the host
side of every bind mount, which would put a service's state outside the workspace and
require root to create — against aisland's rule that service data lives in
``aisland/data/<service>/``. Compose merges a service's ``volumes`` by container TARGET
(verified: an override naming the same target replaces the entry rather than adding a
second), so remapping every host path is exactly what an override is for.

The override is GENERATED from the upstream file rather than hand-written, so bumping
:data:`CLEARML_SERVER_VERSION` cannot leave a stale path list behind.

Unlike the supervised services, the process lifecycle belongs to Docker: ``docker compose
up -d`` / ``down`` own these containers, so this class overrides ``launch`` / ``stop`` /
``status`` instead of registering with process-compose — the same shape
:class:`~aisland.services.docker.DockerService` uses for Colima.
"""

from __future__ import annotations

import hashlib
import shutil
import subprocess
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Dict, List, Optional

import click
import yaml

from aisland.manager import BaseService

#: Pinned upstream release. Bump this AND the digest below in the same edit.
CLEARML_SERVER_VERSION = "v2.4.0"

#: SHA-256 of upstream's ``docker/docker-compose.yml`` at that tag (verified 2026-08-01).
#: A mismatch aborts rather than running an unexpected topology — refresh it with:
#:   curl -sL <COMPOSE_URL> | shasum -a 256
COMPOSE_SHA256 = "c5905340c3edadc3c9b5e065e68437d64e6e697509bc7261973a448b74e74273"

COMPOSE_URL = "https://raw.githubusercontent.com/clearml/clearml-server/{version}/docker/docker-compose.yml"

#: The host-path prefix upstream hardcodes, and which the override rewrites.
UPSTREAM_HOST_ROOT = "/opt/clearml"

DEFAULT_WEB_PORT = 8080
DEFAULT_API_PORT = 8008
DEFAULT_FILES_PORT = 8081

#: Workspace ``.env`` keys a tracker reads to reach this server.
ENV_KEYS = ("CLEARML_WEB_HOST", "CLEARML_API_HOST", "CLEARML_FILES_HOST")

_OVERRIDE_HEADER = """\
# =========================================================================
# AUTO-GENERATED FILE — DO NOT EDIT BY HAND
# Generated by: aisland clearml start
# Source module: aisland/aisland/services/clearml.py (ClearMLService._write_override)
# To regenerate:  aisland clearml reset && aisland clearml start
# =========================================================================
# Layered over upstream's pinned docker-compose.yml. Its ONLY job is to move every
# host bind mount out of /opt/clearml and into this workspace's aisland/data/clearml,
# because service state must not live outside the workspace. Compose merges a
# service's `volumes` by container target, so each entry here REPLACES upstream's.
"""


class ClearMLService(BaseService):
    """ClearML server (upstream docker-compose stack, workspace-local state)."""

    def __init__(self) -> None:
        super().__init__("clearml")
        self.upstream_file = self.service_data_dir / f"docker-compose-{CLEARML_SERVER_VERSION}.yml"
        self.override_file = self.service_data_dir / "aisland-override.yml"
        self.state_dir = self.service_data_dir / "state"

    # -- preconditions --------------------------------------------------------------------

    def setup(self) -> None:
        """Check the backend is SELECTED and Docker is reachable — install neither."""
        import importlib.util

        if importlib.util.find_spec("clearml") is None:
            raise click.ClickException(
                "ClearML is not installed in this environment.\n"
                "  Select it, so the choice is recorded and survives the next setup:\n"
                "      aisland tracker set clearml\n"
                "  Or, for this machine only:\n"
                "      aisland tracker set clearml --machine-only"
            )
        if shutil.which("docker") is None:
            raise click.ClickException(
                "The `docker` CLI was not found.\n"
                "  It is declared in aisland's sys-dependencies; install and link it with:\n"
                "      brew install docker docker-compose && brew link --overwrite docker"
            )
        probe = subprocess.run(["docker", "info"], capture_output=True, text=True)
        if probe.returncode != 0:
            raise click.ClickException(
                "The Docker daemon is not reachable.\n  Start it with:\n      aisland docker start"
            )

    # -- the compose files ----------------------------------------------------------------

    def _fetch_upstream(self) -> Path:
        """Download upstream's compose at the pinned tag, verified, cached.

        Verified BEFORE it is cached: a file that fails the digest is never written where a
        later run could pick it up as though it had been checked.
        """
        if self.upstream_file.exists():
            return self.upstream_file
        url = COMPOSE_URL.format(version=CLEARML_SERVER_VERSION)
        click.echo(f"Fetching clearml-server {CLEARML_SERVER_VERSION} compose...")
        try:
            with urllib.request.urlopen(url, timeout=60) as response:
                payload: bytes = response.read()
        except (urllib.error.URLError, OSError) as exc:
            raise click.ClickException(f"Could not download {url}: {exc}")

        digest = hashlib.sha256(payload).hexdigest()
        if digest != COMPOSE_SHA256:
            raise click.ClickException(
                f"Checksum mismatch for clearml-server {CLEARML_SERVER_VERSION}.\n"
                f"  expected {COMPOSE_SHA256}\n  got      {digest}\n"
                "  Upstream changed the file at this tag, or the download was tampered with.\n"
                "  Verify it yourself before updating COMPOSE_SHA256 in aisland/services/clearml.py."
            )
        self.service_data_dir.mkdir(parents=True, exist_ok=True)
        self.upstream_file.write_bytes(payload)
        return self.upstream_file

    def _write_override(self, upstream: Path) -> Path:
        """Generate the override that moves every host bind mount into the workspace.

        Derived FROM the upstream file rather than hand-listed, so bumping the pinned version
        cannot leave a path behind — a new mount upstream adds is remapped automatically, and
        one it drops simply stops appearing.
        """
        document = yaml.safe_load(upstream.read_text()) or {}
        services: Dict[str, Any] = {}
        for name, spec in (document.get("services") or {}).items():
            remapped = [
                f"{self._relocate(entry.split(':', 1)[0])}:{entry.split(':', 1)[1]}"
                for entry in (spec.get("volumes") or [])
                if isinstance(entry, str) and entry.startswith(UPSTREAM_HOST_ROOT + "/")
            ]
            if remapped:
                services[name] = {"volumes": remapped}

        self.override_file.write_text(
            _OVERRIDE_HEADER + yaml.safe_dump({"services": services}, sort_keys=True, default_flow_style=False)
        )
        return self.override_file

    def _relocate(self, host_path: str) -> str:
        """``/opt/clearml/data/redis`` -> ``<aisland>/data/clearml/state/data/redis``."""
        relative = host_path[len(UPSTREAM_HOST_ROOT) :].lstrip("/")
        target = self.state_dir / relative
        target.mkdir(parents=True, exist_ok=True)
        return str(target)

    def _compose(self, *args: str) -> List[str]:
        return ["docker", "compose", "-f", str(self.upstream_file), "-f", str(self.override_file), *args]

    # -- lifecycle ------------------------------------------------------------------------

    def launch(self, port: int = DEFAULT_WEB_PORT, background: bool = True, **kwargs: Any) -> None:
        """Bring the stack up (always detached — seven containers are not a foreground job)."""
        self.setup()
        upstream = self._fetch_upstream()
        self._write_override(upstream)
        self._publish_env(port)

        click.echo(f"ClearML: http://localhost:{port}")
        click.echo(f"  State: {self.state_dir}")
        try:
            subprocess.check_call(self._compose("up", "-d"))
        except subprocess.CalledProcessError as exc:
            raise click.ClickException(f"`docker compose up` failed: {exc}")
        click.echo("ClearML started. The web UI takes ~30s to answer while Elasticsearch boots.")

    def stop(self) -> None:
        if not self.override_file.exists():
            click.echo("ClearML has never been started here; nothing to stop.")
            return
        subprocess.run(self._compose("down"), check=False)
        click.echo("ClearML stopped.")

    def status(self) -> None:
        if not self.override_file.exists():
            click.echo("  ClearML         : Not configured (run `aisland clearml start`)")
            return
        subprocess.run(self._compose("ps"), check=False)

    def info(self) -> None:
        # NOT `super().info()`: the base prints a "Supervisor: process-compose" line, and these
        # containers are Docker's. Saying otherwise sends an operator to the wrong tool when
        # something is wedged.
        click.echo(f"  Service       : {self.name}")
        click.echo(f"  Data dir      : {self.service_data_dir}")
        click.echo("  Lifecycle     : docker compose (NOT the process-compose supervisor)")
        click.echo(f"  Upstream      : clearml-server {CLEARML_SERVER_VERSION} (sha256 pinned)")
        click.echo(f"  Compose       : {self.upstream_file}")
        click.echo(f"  Override      : {self.override_file}")
        click.echo(f"  State         : {self.state_dir}")
        click.echo(f"  Web / API     : http://localhost:{DEFAULT_WEB_PORT} / :{DEFAULT_API_PORT}")

    def reset(self) -> None:
        """Tear the stack down and delete its state, compose files and volumes."""
        if self.override_file.exists():
            subprocess.run(self._compose("down", "-v"), check=False)
        for path in (self.upstream_file, self.override_file):
            path.unlink(missing_ok=True)
        if self.state_dir.exists():
            shutil.rmtree(self.state_dir)
        click.echo("ClearML state removed.")

    # -- workspace wiring -----------------------------------------------------------------

    def _publish_env(self, web_port: int) -> None:
        """Record the three hosts a ``ClearMLTracker`` reads, in the workspace ``.env``."""
        from aisland.manager import get_workspace_root

        values = {
            "CLEARML_WEB_HOST": f"http://localhost:{web_port}",
            "CLEARML_API_HOST": f"http://localhost:{DEFAULT_API_PORT}",
            "CLEARML_FILES_HOST": f"http://localhost:{DEFAULT_FILES_PORT}",
        }
        env_file = get_workspace_root() / ".env"
        lines = env_file.read_text().splitlines() if env_file.exists() else []
        for key, value in values.items():
            entry = f"{key}={value}"
            for index, existing in enumerate(lines):
                if existing.strip().startswith(f"{key}="):
                    lines[index] = entry
                    break
            else:
                lines.append(entry)
        env_file.write_text("\n".join(lines) + "\n")


def resolve_state_dir(service: Optional[ClearMLService] = None) -> Path:
    """The workspace-local root every ClearML bind mount is redirected into."""
    return (service or ClearMLService()).state_dir
