"""Which ML frameworks this workspace installs (``aisland framework``).

The workspace's packages are framework-neutral at the core and put every framework behind an
EXTRA — ``recordstream[torch]``, ``sonair[lightning]`` / ``[keras]``, ``marainer[torch,keras,…]``.
That makes "install only what I work with" expressible, but only if something decides WHICH.
Before this module, ``aisland setup`` installed ``<project>[dev]`` and nothing else, so after the
extras split a fresh setup produced a sonair with no backend at all.

Two halves, deliberately separate:

* **A project DECLARES which of its extras are frameworks**, in its own ``pyproject.toml``::

      [tool.aisland]
      frameworks = ["lightning", "keras"]

  It has to be declared rather than guessed, because extras are a mixed bag — ``dev``, ``http``,
  ``viz``, ``notebook``, ``all`` sit in the same table as ``torch`` and ``keras``, and a name
  match would install a documentation extra on a machine that asked for a training engine. Only
  IMPLEMENTED frameworks belong here: sonair keeps ``jax`` / ``mlx`` / ``huggingface`` extras so
  its CLI templates have a name to point at, but declaring them would install three unused
  frameworks. Declaring is not the same as installing — the declaration is the MENU, and the
  workspace's committed SELECTION decides what lands (sonair declares ``tensorflow`` since its
  backend became real on 2026-07-30, and the workspace does not select it simply because nothing
  else needs a second engine's worth of download).

* **The workspace SELECTS framework names**, and each project installs the extras it declares
  that are selected. The names line up across projects on purpose (``keras`` is ``keras``
  everywhere), so ONE selection drives every project without a per-project mapping table.

Two configuration layers, mirroring :mod:`aisland.sources` exactly:

* **committed** — ``<workspace>/frameworks.toml`` (tracked, shared between machines,
  and the ONLY layer generated CI reads);
* **per-machine** — ``git config --local aisland.frameworks`` (never committed).

The split is the same one :mod:`aisland.sources` documents, for the same reason: a machine-local
choice must never reach a committed artifact. A developer who never touches TensorFlow drops it
locally; CI still installs the committed set and keeps every backend tested. Verified 2026-07-30
that the full set co-resolves (torch 2.13 + tensorflow 2.20 + keras 3.15 + pytorch-lightning
2.6.5 on one numpy), so "CI installs everything" is a real option and not merely a wish.

An UNSET selection is not the same as an empty one. Empty means "no frameworks, I mean it";
unset means nobody has chosen yet, and :func:`aisland.manager.setup_workspace` prompts (recording
the answer) rather than silently installing either everything or nothing.
"""

from __future__ import annotations

import subprocess
import tomllib
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import click

from aisland.manager import get_workspace_root

#: Committed, workspace-root framework selection.
FRAMEWORKS_FILE = "frameworks.toml"

#: The ``pyproject.toml`` table a project declares its framework extras in.
DECLARATION_TABLE = ("tool", "aisland", "frameworks")

#: ``.git/config`` key holding the per-machine override (space-separated names).
CONFIG_KEY = "aisland.frameworks"

_HEADER = """\
# =========================================================================
# AUTO-GENERATED / MANAGED FILE — prefer `aisland framework set` over hand edits.
# Generated by: aisland framework set <name>...
# Source module: aisland/aisland/frameworks.py (write_committed_frameworks)
# To inspect:    aisland framework list
# =========================================================================
# The COMMITTED ML-framework selection (shared between machines, and the set every
# generated CI pipeline installs). Each workspace project installs the extras it
# declares under `[tool.aisland] frameworks` that appear in this list — so a project
# that declares none is unaffected, and a name no project declares is simply inert.
#
# Per-machine deviations live in `.git/config` as `aisland.frameworks` and are
# deliberately NOT recorded here; use `aisland framework set --machine-only <name>...`.
#
#   aisland framework list                   the declarations, the selection, and the effect
#   aisland framework set torch keras        replace the committed selection and install it
#   aisland framework set --machine-only ... override on THIS machine only
#   aisland framework unset --machine-only   drop the override, fall back to committed
"""


# --------------------------------------------------------------------------- #
# What each project declares
# --------------------------------------------------------------------------- #


def declared_frameworks(pyproject_path: Path) -> List[str]:
    """The framework extras a project declares, in declaration order.

    Reads ``[tool.aisland] frameworks``. A project with no declaration returns ``[]`` and is
    therefore unaffected by any selection — which is what keeps this change inert for the
    fifteen-odd projects that ship no framework extra.

    Example::

        declared_frameworks(Path("sonair/pyproject.toml"))  # ["lightning", "keras"]
    """
    try:
        data = tomllib.loads(pyproject_path.read_text())
    except (OSError, tomllib.TOMLDecodeError):
        return []
    node: object = data
    for key in DECLARATION_TABLE:
        if not isinstance(node, dict):
            return []
        node = node.get(key, {})
    if not isinstance(node, list):
        return []
    return [str(name) for name in node]


def declarations(workspace_root: Path) -> Dict[str, List[str]]:
    """``{project name: declared framework extras}`` for every project that declares any.

    Discovery goes through :func:`aisland.manager.discover_projects`, so a project detached by
    ``aisland source set … pypi`` (empty directory, no pyproject) drops out on its own.
    """
    from aisland.manager import discover_projects

    out: Dict[str, List[str]] = {}
    for pyproject in discover_projects(workspace_root):
        names = declared_frameworks(pyproject)
        if names:
            out[pyproject.parent.name] = names
    return out


def available_frameworks(workspace_root: Path) -> List[str]:
    """Every framework name declared by any project, sorted — the selectable vocabulary."""
    return sorted({name for names in declarations(workspace_root).values() for name in names})


# --------------------------------------------------------------------------- #
# committed layer: frameworks.toml
# --------------------------------------------------------------------------- #


def read_committed_frameworks(workspace_root: Path) -> Optional[List[str]]:
    """The committed selection, or ``None`` when the file does not exist.

    ``None`` (unset) is distinct from ``[]`` (explicitly no frameworks) — setup prompts for the
    former and honours the latter.
    """
    path = workspace_root / FRAMEWORKS_FILE
    if not path.exists():
        return None
    try:
        data = tomllib.loads(path.read_text())
    except (OSError, tomllib.TOMLDecodeError) as exc:
        click.echo(f"  - Warning: could not read {FRAMEWORKS_FILE}: {exc}")
        return None
    selected = data.get("frameworks", [])
    return [str(name) for name in selected] if isinstance(selected, list) else []


def write_committed_frameworks(workspace_root: Path, names: Sequence[str]) -> Path:
    """Write the committed selection, preserving the managed-file header."""
    path = workspace_root / FRAMEWORKS_FILE
    rendered = ", ".join(f'"{name}"' for name in names)
    path.write_text(f"{_HEADER}\nframeworks = [{rendered}]\n")
    return path


# --------------------------------------------------------------------------- #
# per-machine layer: .git/config aisland.frameworks
# --------------------------------------------------------------------------- #


def local_override(workspace_root: Path) -> Optional[List[str]]:
    """The per-machine selection from ``.git/config``, or ``None`` when unset.

    Stored space-separated in one key rather than one key per framework: the value is a SET
    being replaced wholesale, and a multi-key form would make "none selected" indistinguishable
    from "never chosen" — the very distinction this module is careful about.
    """
    try:
        result = subprocess.run(
            ["git", "config", "--local", "--get", CONFIG_KEY],
            cwd=workspace_root,
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        return None
    if result.returncode != 0:
        return None
    return result.stdout.split()


def set_local_override(workspace_root: Path, names: Optional[Sequence[str]]) -> None:
    """Set (or, with ``names=None``, remove) the per-machine selection."""
    if names is None:
        subprocess.run(
            ["git", "config", "--local", "--unset", CONFIG_KEY],
            cwd=workspace_root,
            capture_output=True,
        )
        return
    subprocess.run(
        ["git", "config", "--local", CONFIG_KEY, " ".join(names)],
        cwd=workspace_root,
        check=True,
        capture_output=True,
    )


# --------------------------------------------------------------------------- #
# the resolved answer
# --------------------------------------------------------------------------- #


def effective_frameworks(workspace_root: Path) -> Optional[List[str]]:
    """The selection that drives the venv: the per-machine override, else the committed one.

    ``None`` means nobody has chosen on this machine or in this repo — the caller decides what
    to do about it (setup prompts; CI uses the committed layer, which is never ``None`` in a
    repo that has run ``aisland framework set``).
    """
    override = local_override(workspace_root)
    return override if override is not None else read_committed_frameworks(workspace_root)


def extras_for(project_name: str, declared: Sequence[str], selected: Optional[Sequence[str]]) -> List[str]:
    """The framework extras to install for one project: what it declares ∩ what is selected.

    Order follows the project's DECLARATION, not the selection, so the emitted install target is
    stable regardless of the order names were typed in. An unset selection (``None``) yields
    nothing — callers that mean "everything" pass the full list explicitly, so the ambiguity
    never travels.

    Example::

        extras_for("sonair", ["lightning", "keras"], ["keras", "torch"])  # ["keras"]
    """
    if not selected:
        return []
    chosen = set(selected)
    return [name for name in declared if name in chosen]


def install_target(project_dir: Path, has_dev: bool, extras: Sequence[str]) -> str:
    """The ``uv pip install -e`` target for one project, e.g. ``/w/sonair[dev,lightning]``.

    Kept here rather than inlined at the two call sites (the venv install and the generated CI
    lines) so both spell the extras list identically — they are compared by eye when a build
    disagrees with a local run.
    """
    parts = (["dev"] if has_dev else []) + list(extras)
    return f"{project_dir}[{','.join(parts)}]" if parts else str(project_dir)


# --------------------------------------------------------------------------- #
# the setup prompt
# --------------------------------------------------------------------------- #


def prompt_for_frameworks(workspace_root: Path, available: Sequence[str]) -> List[str]:
    """Ask which frameworks to install, returning the chosen names.

    Blank answer selects EVERYTHING, because the alternative default (nothing) hands back a
    workspace whose training projects cannot run — a fresh setup should work before it is
    optimised. Answers are matched by name or by 1-based index, so both
    ``torch keras`` and ``1,3`` work.
    """
    click.echo("\n==> Which ML frameworks should this machine install?")
    click.echo("    (workspace projects put each framework behind an extra; this selects them)")
    for index, name in enumerate(available, start=1):
        users = [p for p, names in declarations(workspace_root).items() if name in names]
        click.echo(f"      [{index}] {name:<12} {', '.join(sorted(users))}")
    answer = click.prompt(
        "    Select (names or numbers, comma/space separated; blank = all)",
        default="",
        show_default=False,
    )
    return parse_selection(answer, available)


def parse_selection(answer: str, available: Sequence[str]) -> List[str]:
    """Parse a prompt answer into framework names; blank means all of ``available``.

    Unknown tokens are DROPPED with a warning rather than raising: this runs in the middle of a
    long ``aisland setup``, and aborting a provisioning run over a typo would cost more than
    proceeding with the names that were understood.
    """
    tokens = [tok for tok in answer.replace(",", " ").split() if tok]
    if not tokens:
        return list(available)
    chosen: List[str] = []
    for token in tokens:
        if token.isdigit() and 1 <= int(token) <= len(available):
            name = available[int(token) - 1]
        elif token in available:
            name = token
        else:
            click.echo(f"  - Warning: unknown framework {token!r}; ignoring.")
            continue
        if name not in chosen:
            chosen.append(name)
    return chosen


def resolve_for_setup(
    workspace_root: Path,
    requested: Optional[Sequence[str]],
    non_interactive: bool,
) -> Tuple[List[str], bool]:
    """The framework selection ``setup`` should install, plus whether it was just chosen.

    Precedence: an explicit ``--framework`` flag wins and is RECORDED (so the next run needs no
    flag); else an existing selection is used as-is; else the operator is prompted, unless the
    run is non-interactive, in which case everything available is selected — a headless setup
    must not hang, and must not silently produce a workspace that cannot train.
    """
    available = available_frameworks(workspace_root)
    if not available:
        return [], False

    if requested:
        chosen = parse_selection(" ".join(requested), available)
        write_committed_frameworks(workspace_root, chosen)
        return chosen, True

    existing = effective_frameworks(workspace_root)
    if existing is not None:
        return list(existing), False

    if non_interactive:
        click.echo(f"==> No framework selection recorded; installing all ({', '.join(available)}).")
        write_committed_frameworks(workspace_root, available)
        return available, True

    chosen = prompt_for_frameworks(workspace_root, available)
    write_committed_frameworks(workspace_root, chosen)
    click.echo(f"  - Recorded in {FRAMEWORKS_FILE}: {', '.join(chosen) or '(none)'}")
    return chosen, True


# --------------------------------------------------------------------------- #
# the CLI surface
# --------------------------------------------------------------------------- #


def describe(workspace_root: Optional[Path] = None) -> List[Dict[str, str]]:
    """One row per declared framework: who offers it, and whether each layer selects it.

    Rows are per FRAMEWORK rather than per project because that is the unit an operator selects;
    the projects affected are shown as a column so the effect of a choice is visible without a
    second command.
    """
    root = workspace_root or get_workspace_root()
    decls = declarations(root)
    committed = read_committed_frameworks(root)
    override = local_override(root)
    effective = effective_frameworks(root)

    def mark(selection: Optional[Sequence[str]], name: str) -> str:
        if selection is None:
            return "-"
        return "yes" if name in selection else "no"

    return [
        {
            "framework": name,
            "committed": mark(committed, name),
            "override": mark(override, name),
            "effective": mark(effective, name),
            "projects": ", ".join(sorted(p for p, names in decls.items() if name in names)),
        }
        for name in available_frameworks(root)
    ]


def apply_frameworks(workspace_root: Path, selected: Sequence[str], uv_cmd: Optional[str] = None) -> int:
    """Reinstall every project that declares a framework, at the current selection.

    Only DECLARING projects are touched: reinstalling the whole workspace to change one extra
    would take minutes and rebuild things the selection cannot affect. Returns the number of
    projects that failed to install, so the CLI can exit non-zero.

    Order comes from :func:`aisland.manager.get_install_order` — the same topological order
    ``aisland setup`` uses — NOT from discovery order. That is load-bearing rather than tidy: a
    consumer's extra can name a sibling's extra (``sonair[keras]`` requires
    ``marainer[keras]>=0.1.0``), so installing the consumer first resolves it against the
    sibling's ALREADY-INSTALLED metadata and uv warns ``does not have an extra named 'keras'``
    while quietly installing without it. Observed on the first real run of this function.

    uv does not UNINSTALL an extra that is no longer selected — dropping ``keras`` leaves the
    keras wheel in the venv until something removes it. That is deliberate: guessing which
    packages "belonged" to an extra is unsound (they are ordinary dependencies, possibly shared),
    and a stale wheel costs disk, not correctness. Recreate the venv for a truly clean set.
    """
    from aisland.manager import ensure_uv_in_venv, get_install_order

    uv = uv_cmd or ensure_uv_in_venv(workspace_root / ".venv" / "bin")
    failures = 0
    for project in get_install_order(workspace_root):
        declared = declared_frameworks(project["path"] / "pyproject.toml")
        if not declared:
            continue
        extras = extras_for(project["name"], declared, selected)
        target = install_target(project["path"], project["has_dev"], extras)
        click.echo(f"==> Installing {project['name']} ({target})...")
        try:
            subprocess.check_call([uv, "pip", "install", "-e", target], cwd=workspace_root)
        except subprocess.CalledProcessError as exc:
            click.echo(f"  - Error: Failed to install {project['name']}: {exc}")
            failures += 1
    return failures


def set_frameworks(names: Sequence[str], machine_only: bool = False, apply: bool = True) -> int:
    """Record a framework selection and (by default) install it. Returns an exit code."""
    workspace_root = get_workspace_root()
    available = available_frameworks(workspace_root)
    if not available:
        click.echo("No project declares any framework extras ([tool.aisland] frameworks); nothing to select.")
        return 1

    unknown = [name for name in names if name not in available]
    if unknown:
        click.echo(f"Error: unknown framework(s) {', '.join(unknown)}. Available: {', '.join(available)}")
        return 1

    chosen = list(dict.fromkeys(names))
    if machine_only:
        set_local_override(workspace_root, chosen)
        click.echo(f"==> This machine only: {', '.join(chosen) or '(none)'}")
    else:
        path = write_committed_frameworks(workspace_root, chosen)
        click.echo(f"==> Recorded in {path.name}: {', '.join(chosen) or '(none)'}")
        if local_override(workspace_root) is not None:
            click.echo("  - Note: a per-machine override is set and still WINS here.")
            click.echo("    Drop it with: aisland framework unset --machine-only")

    return apply_frameworks(workspace_root, effective_frameworks(workspace_root) or []) if apply else 0


def unset_frameworks(machine_only: bool = False, apply: bool = True) -> int:
    """Clear a selection: the per-machine override, or (default) the committed file too."""
    workspace_root = get_workspace_root()
    set_local_override(workspace_root, None)
    if machine_only:
        click.echo("==> Cleared this machine's override; the committed selection applies.")
    else:
        path = workspace_root / FRAMEWORKS_FILE
        if path.exists():
            path.unlink()
        click.echo(f"==> Cleared the override and removed {FRAMEWORKS_FILE}; setup will prompt again.")

    selection = effective_frameworks(workspace_root)
    if selection is None or not apply:
        return 0
    return apply_frameworks(workspace_root, selection)
