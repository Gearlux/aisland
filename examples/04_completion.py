"""`aisland completion install --target-rc FILE` — the completion file it writes, and what it does when sourced.

`aisland completion install` writes shell completion for every command-line tool of the workspace's virtual
environment into one file a shell sources at start-up. It works on a workspace, so the example makes a throwaway
one (`aisland workspace init`) and writes a temporary file: your own workspace and shell's files are untouched.

It shows, and asserts:

- the file says which command wrote it and how to write it again;
- it holds aisland's own completion;
- sourced by a shell that is NOT interactive (a script, `bash -c`), it runs no program — aisland's completion
  lines run `aisland` to get its script, and a non-interactive shell has no use for them;
- running the command again rewrites the file in place: aisland's block is there once.

No network: `python examples/04_completion.py`. The page: docs/completion.md.
"""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path

AISLAND = str(Path(sys.executable).with_name("aisland"))


def main() -> None:
    with tempfile.TemporaryDirectory() as scratch:
        made = subprocess.run(
            [AISLAND, "workspace", "init", "acme"], cwd=scratch, capture_output=True, text=True, timeout=300
        )
        assert made.returncode == 0, made.stdout + made.stderr
        rc = Path(scratch) / "completion.bash"
        for _ in range(2):
            result = subprocess.run(
                [AISLAND, "completion", "install", "--target-rc", str(rc), "--shell", "bash"],
                cwd=Path(scratch) / "acme",
                capture_output=True,
                text=True,
                timeout=600,
            )
            assert result.returncode == 0, result.stdout + result.stderr
        print(result.stdout)
        text = rc.read_text()

        assert "# Generated by: aisland completion install" in text, "the file names the command that wrote it"
        assert "_AISLAND_COMPLETE=bash_source aisland" in text, "aisland's own completion is in it"
        assert text.count("_AISLAND_COMPLETE=bash_source aisland") == 1, "a second install rewrote it in place"

        # A stand-in `aisland` first on PATH records every run: the file's aisland block runs `aisland` to get its
        # script, which a non-interactive shell must never do.
        stand_in = Path(scratch) / "bin"
        stand_in.mkdir()
        ran = Path(scratch) / "ran"
        (stand_in / "aisland").write_text(f'#!/bin/sh\necho aisland >> "{ran}"\n')
        (stand_in / "aisland").chmod(0o755)
        sourced = subprocess.run(
            ["bash", "-c", f'source "{rc}"; echo "sourced"'],
            env={**os.environ, "PATH": f"{stand_in}{os.pathsep}{os.environ['PATH']}"},
            capture_output=True,
            text=True,
            timeout=30,
        )
        assert sourced.stdout.strip() == "sourced", sourced.stdout + sourced.stderr
        assert not ran.exists(), "a non-interactive shell sourcing the file ran aisland"
    print(f"completion file written ({len(text.splitlines())} lines); a non-interactive shell runs no program from it")


if __name__ == "__main__":
    main()
